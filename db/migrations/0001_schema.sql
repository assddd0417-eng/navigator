     LEFT JOIN ax.program p ON ((p.id = a.program_id)));

CREATE VIEW ax.v_company_field_compare AS
 SELECT organization_id,
    field_name,
    (array_agg(value ORDER BY is_verified DESC, (source_kind = 'EXTERNAL'::text) DESC, recorded_at DESC))[1] AS preferred_value,
    bool_or(is_verified) AS any_verified,
    (count(DISTINCT value) > 1) AS differs,
    jsonb_agg(jsonb_build_object('source_kind', source_kind, 'external_source_id', external_source_id, 'value', value, 'is_verified', is_verified, 'recorded_at', recorded_at) ORDER BY is_verified DESC, (source_kind = 'EXTERNAL'::text) DESC, recorded_at DESC) AS sources
   FROM ax.company_field_source
  GROUP BY organization_id, field_name;

