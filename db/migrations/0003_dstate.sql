CREATE TABLE ax.company_dstate_value (
    organization_id bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    variable_code   text NOT NULL REFERENCES ax.dstate_variable(code),
    origin          text NOT NULL CHECK (origin IN ('SELF', 'STAFF')),
    value           jsonb NOT NULL,
    note            text,
    updated_by      bigint REFERENCES ax.app_user(id),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, variable_code, origin)
);

COMMENT ON TABLE ax.company_dstate_value IS '진단 변수 보완값. 담당자 값(STAFF)이 있으면 그 값을 쓴다';

CREATE TABLE ax.company_diagnosis (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    rule_version    text NOT NULL,
    total_score     smallint NOT NULL CHECK (total_score BETWEEN 0 AND 100),
    state_type      text NOT NULL,
    weakest_area    text NOT NULL,
    scores          jsonb NOT NULL,
    inputs          jsonb NOT NULL,
    missing         text[] NOT NULL DEFAULT '{}',
    summary         text NOT NULL,
    created_by      bigint REFERENCES ax.app_user(id),
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX company_diagnosis_org ON ax.company_diagnosis (organization_id, created_at DESC);

COMMENT ON TABLE ax.company_diagnosis IS 'D-STATE 진단 이력. 같은 입력이면 같은 점수 (rule_version 기준)';

CREATE TRIGGER trg_company_dstate_value_audit AFTER INSERT OR DELETE OR UPDATE ON ax.company_dstate_value
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row('organization_id', 'variable_code', 'origin');
