CREATE TABLE ax.user_role (
    user_id    bigint NOT NULL REFERENCES ax.app_user(id) ON DELETE CASCADE,
    role_code  text   NOT NULL REFERENCES ax.app_role(code),
    granted_at timestamptz NOT NULL DEFAULT now(),
    granted_by bigint REFERENCES ax.app_user(id),
    PRIMARY KEY (user_id, role_code)
);

-- 사용자/부서 단위 열람 범위: 특정 부서 소관 자료 열람 허용 (원천시스템 권한 반영)
CREATE TABLE ax.department_access_grant (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grantee_user_id    bigint REFERENCES ax.app_user(id) ON DELETE CASCADE,
    grantee_dept_id    bigint REFERENCES ax.department(id) ON DELETE CASCADE,
    target_dept_id     bigint NOT NULL REFERENCES ax.department(id) ON DELETE CASCADE,
    max_security_code  text NOT NULL REFERENCES ax.code_security_level(code),
    valid_from         timestamptz NOT NULL DEFAULT now(),
    valid_to           timestamptz,
    source_system_code text REFERENCES ax.code_source_system(code),  -- 권한 원천
    CHECK (num_nonnulls(grantee_user_id, grantee_dept_id) = 1)
);
COMMENT ON TABLE ax.department_access_grant IS
  '타 부서 소관 자료 열람권한. 자기 부서 자료는 사용자 clearance 범위에서 기본 허용';
