SET search_path = ax, public;

-- 기관 (주관기관·참여기관·방산기업·연구기관·군 등 외부/내부 기관 통합)
CREATE TABLE ax.organization (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_code        text UNIQUE,                       -- 원천시스템 기관코드
    name            text NOT NULL,
    org_type        text NOT NULL CHECK (org_type IN
                     ('COMPANY','RESEARCH_INSTITUTE','UNIVERSITY','GOVERNMENT','MILITARY','INTERNAL','OTHER')),
    business_reg_no text UNIQUE,                       -- 사업자등록번호 (기업 식별 기준정보)
    parent_id       bigint REFERENCES ax.organization(id),
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX organization_name_trgm ON ax.organization USING gin (name gin_trgm_ops);
CREATE TRIGGER trg_organization_updated BEFORE UPDATE ON ax.organization
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();
COMMENT ON TABLE ax.organization IS '기관 Master (기업은 company_profile 로 확장)';

-- 연구소 내부 부서 (담당부서·협업부서 후보의 대상)
CREATE TABLE ax.department (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_code   text NOT NULL UNIQUE,
    name        text NOT NULL,
    parent_id   bigint REFERENCES ax.department(id),
    description text,                                  -- 소관 기술분야·업무 (부서 추천용)
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_department_updated BEFORE UPDATE ON ax.department
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 사용자
CREATE TABLE ax.app_user (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id         text NOT NULL UNIQUE,              -- SSO/사번 등 외부 인증 식별자
    name             text NOT NULL,
    email            text,
    department_id    bigint REFERENCES ax.department(id),
    organization_id  bigint REFERENCES ax.organization(id),  -- 외부 전문가 소속
    clearance_code   text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    expertise        text,                              -- 전문분야 (전문가 배정용)
    is_external      boolean NOT NULL DEFAULT false,
    is_active        boolean NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX app_user_department ON ax.app_user(department_id);
CREATE TRIGGER trg_app_user_updated BEFORE UPDATE ON ax.app_user
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

CREATE TABLE ax.app_role (
    code        text PRIMARY KEY,
    name_ko     text NOT NULL,
    description text
);
