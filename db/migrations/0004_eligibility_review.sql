-- 지원사업 자격검토: 공고문 점검 항목 (신청제한·평가기준·우대 가점·기업부담·제출서류)
--   announcement_eval_item   평가항목·배점과 연결할 D-STATE 영역 (적합도 산정)
--   DUPLICATE_SUPPORT        유사·중복 지원 제한 (신청제한)
--   procurement_sanctioned   조달청 부정당제재 (조달청 연동 예정, 지금은 기업·담당자 입력)
SET search_path = ax, public;

ALTER TABLE ax.company_profile ADD COLUMN procurement_sanctioned boolean;
COMMENT ON COLUMN ax.company_profile.procurement_sanctioned IS '부정당제재 여부. 조달청 연동 전까지 기업·담당자 입력';

ALTER TABLE ax.announcement
    ADD COLUMN company_burden text,
    ADD COLUMN submit_documents jsonb NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(submit_documents) = 'array');
COMMENT ON COLUMN ax.announcement.company_burden IS '기업부담 (예: 컨설팅 비용 25%)';
COMMENT ON COLUMN ax.announcement.submit_documents IS '제출서류 [{"name":"중소기업확인서","required":true}]';

ALTER TABLE ax.announcement_requirement
    ADD COLUMN bonus_points numeric(5,2) CHECK (bonus_points IS NULL OR bonus_points >= 0);
COMMENT ON COLUMN ax.announcement_requirement.bonus_points IS '우대 요건 충족 시 적합도 가점';

CREATE TABLE ax.announcement_eval_item (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    name            text NOT NULL,
    points          numeric(5,2) NOT NULL CHECK (points > 0),
    kind            text NOT NULL CHECK (kind IN ('CAPABILITY', 'PURPOSE', 'APPLICATION')),
    areas           text[] NOT NULL DEFAULT '{}',
    source_quote    text,
    source_page     integer CHECK (source_page > 0),
    sort_order      smallint NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (kind <> 'CAPABILITY' OR cardinality(areas) > 0),
    CHECK (areas <@ ARRAY['TECH', 'QUALITY', 'PRODUCTION', 'BUSINESS', 'DEFENSE', 'EXPORT']::text[])
);
CREATE INDEX announcement_eval_item_ann ON ax.announcement_eval_item (announcement_id, sort_order);

COMMENT ON TABLE ax.announcement_eval_item IS
    '공고 평가항목·배점. CAPABILITY = D-STATE 영역 점수로 평가, PURPOSE = 상담 내용과 사업 목적 비교, APPLICATION = 신청서 기반이라 상담 단계 제외';

CREATE TRIGGER trg_announcement_eval_item_audit AFTER INSERT OR DELETE OR UPDATE ON ax.announcement_eval_item
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();

