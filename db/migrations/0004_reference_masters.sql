SET search_path = ax, public;

-- 국방기술 분류체계 (계층형)
CREATE TABLE ax.tech_taxonomy (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    name        text NOT NULL,
    parent_id   bigint REFERENCES ax.tech_taxonomy(id),
    level       smallint NOT NULL DEFAULT 1,
    description text,
    is_active   boolean NOT NULL DEFAULT true
);
CREATE INDEX tech_taxonomy_parent ON ax.tech_taxonomy(parent_id);

-- 무기체계 Master
CREATE TABLE ax.weapon_system (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_code   text NOT NULL UNIQUE,                -- DTiMS 체계 코드
    name          text NOT NULL,
    category      text,                                -- 지휘통제/기동/화력/항공/해양/방호 등
    parent_id     bigint REFERENCES ax.weapon_system(id),
    description   text,
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX weapon_system_name_trgm ON ax.weapon_system USING gin (name gin_trgm_ops);
CREATE TRIGGER trg_weapon_system_updated BEFORE UPDATE ON ax.weapon_system
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 품목 Master (부품 포함)
CREATE TABLE ax.item (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_no        text NOT NULL UNIQUE,               -- 품목번호 (재고번호/NSN 등 기준번호)
    name           text NOT NULL,
    classification text,                               -- 품목 분류
    is_part        boolean NOT NULL DEFAULT false,
    is_imported    boolean,                            -- 수입품 여부 (부품국산화 후보 판단)
    description    text,
    security_code  text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    is_active      boolean NOT NULL DEFAULT true,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX item_name_trgm ON ax.item USING gin (name gin_trgm_ops);
CREATE TRIGGER trg_item_updated BEFORE UPDATE ON ax.item
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 품목-무기체계 관계 (해당 체계에 사용되는 품목)
CREATE TABLE ax.weapon_system_item (
    weapon_system_id bigint NOT NULL REFERENCES ax.weapon_system(id) ON DELETE CASCADE,
    item_id          bigint NOT NULL REFERENCES ax.item(id) ON DELETE CASCADE,
    PRIMARY KEY (weapon_system_id, item_id)
);

-- BOM (상위 품목 - 하위 품목)
CREATE TABLE ax.item_bom (
    parent_item_id bigint NOT NULL REFERENCES ax.item(id) ON DELETE CASCADE,
    child_item_id  bigint NOT NULL REFERENCES ax.item(id) ON DELETE CASCADE,
    quantity       numeric(12,3),
    unit           text,
    source_system_code text REFERENCES ax.code_source_system(code),
    PRIMARY KEY (parent_item_id, child_item_id),
    CHECK (parent_item_id <> child_item_id)
);
CREATE INDEX item_bom_child ON ax.item_bom(child_item_id);

-- 국방기술 동의어 사전 (부서·시스템별 용어 차이 보정)
CREATE TABLE ax.term_synonym (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_term  text NOT NULL,                     -- 표준 용어
    synonym         text NOT NULL,                     -- 동의어/유사어/약어
    relation        text NOT NULL DEFAULT 'SYNONYM'
                    CHECK (relation IN ('SYNONYM','ABBREVIATION','BROADER','NARROWER','RELATED','EN_KO')),
    tech_taxonomy_id bigint REFERENCES ax.tech_taxonomy(id),
    domain          text,                              -- 적용 분야
    source_note     text,                              -- 출처(부서/전문가/문서)
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (canonical_term, synonym)
);
CREATE INDEX term_synonym_syn_trgm ON ax.term_synonym USING gin (synonym gin_trgm_ops);
CREATE INDEX term_synonym_canonical ON ax.term_synonym (canonical_term);

-- 시스템 간 식별자 매핑 (과제번호 Master 등: PMS/DTiMS/DSIS 의 서로 다른 ID 연결)
CREATE TABLE ax.external_id_map (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type        text NOT NULL CHECK (entity_type IN
                        ('PROJECT','ORGANIZATION','ITEM','WEAPON_SYSTEM','PROGRAM','DOCUMENT','DEPARTMENT')),
    entity_id          bigint NOT NULL,
    source_system_code text NOT NULL REFERENCES ax.code_source_system(code),
    external_id        text NOT NULL,
    is_primary         boolean NOT NULL DEFAULT false,
    mapped_by          text NOT NULL DEFAULT 'MANUAL' CHECK (mapped_by IN ('MANUAL','RULE','AI')),
    confidence         real CHECK (confidence BETWEEN 0 AND 1),
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (entity_type, source_system_code, external_id)
);
CREATE INDEX external_id_map_entity ON ax.external_id_map(entity_type, entity_id);

-- 사업트랙 Master
CREATE TABLE ax.program (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code      text NOT NULL UNIQUE,             -- 사업 ID
    name              text NOT NULL,
    program_type_code text NOT NULL REFERENCES ax.code_program_type(code),
    parent_id         bigint REFERENCES ax.program(id),  -- 상위사업
    purpose           text,                             -- 사업 목적·정책목표
    support_scope     text,                             -- 지원범위
    target_desc       text,                             -- 지원대상
    period_start      date,
    period_end        date,
    owner_dept_id     bigint REFERENCES ax.department(id),
    is_active         boolean NOT NULL DEFAULT true,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_program_updated BEFORE UPDATE ON ax.program
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 사업트랙 적용조건 (연계 가능 조건·제약). 근거 문서·청크 FK 는 0007 에서 추가
CREATE TABLE ax.program_condition (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id      bigint NOT NULL REFERENCES ax.program(id) ON DELETE CASCADE,
    condition_type  text NOT NULL CHECK (condition_type IN
                     ('TRL_RANGE','DEV_STAGE','ORG_TYPE','WEAPON_SYSTEM','ITEM_CLASS','BUDGET','PERIOD','EXPORT','OTHER')),
    rule            jsonb NOT NULL DEFAULT '{}'::jsonb, -- 예: {"trl_min":4,"trl_max":7}, {"org_types":["COMPANY"]}
    description     text NOT NULL,
    is_mandatory    boolean NOT NULL DEFAULT true,
    valid_from      date,
    valid_to        date,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX program_condition_program ON ax.program_condition(program_id);

-- 연계 규칙 / 점수 가중치 (Rule Master). 버전별 보관, 매칭 실행 시 스냅샷 기록
CREATE TABLE ax.linkage_rule (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linkage_type_code text NOT NULL REFERENCES ax.code_linkage_type(code),
    version           integer NOT NULL,
    weights           jsonb NOT NULL,     -- {"tech":0.4,"performance":0.15,"trl":0.15,"environment":0.15,"purpose":0.15}
    conditions        jsonb NOT NULL DEFAULT '{}'::jsonb, -- 유형 판정 조건 (예: 후속형은 미해결 기술 유사도 >= 0.6)
    description       text,
    is_active         boolean NOT NULL DEFAULT false,
    created_by        bigint REFERENCES ax.app_user(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (linkage_type_code, version)
);
-- 유형별 활성 규칙은 1개
CREATE UNIQUE INDEX linkage_rule_one_active ON ax.linkage_rule(linkage_type_code) WHERE is_active;

