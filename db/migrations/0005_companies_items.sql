-- 0005: 기업·품목·수출 정보 (Company Master 확장)
-- =============================================================================
SET search_path = ax, public;

-- 기업 상세 (organization.org_type = 'COMPANY' 의 1:1 확장)
CREATE TABLE ax.company_profile (
    organization_id     bigint PRIMARY KEY REFERENCES ax.organization(id) ON DELETE CASCADE,
    is_defense_company  boolean NOT NULL DEFAULT false,  -- 방산업체 지정 여부
    company_size        text CHECK (company_size IN ('LARGE','MIDSIZE','SME','STARTUP','VENTURE')),
    main_business       text,
    homepage            text,
    dsis_company_id     text UNIQUE,                     -- 방위산업정보시스템 기업 ID
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_company_profile_updated BEFORE UPDATE ON ax.company_profile
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 기업 보유기술
CREATE TABLE ax.company_technology (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    tech_name        text NOT NULL,
    description      text,
    tech_taxonomy_id bigint REFERENCES ax.tech_taxonomy(id),
    source_system_code text REFERENCES ax.code_source_system(code),
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX company_technology_org ON ax.company_technology(organization_id);
CREATE INDEX company_technology_name_trgm ON ax.company_technology USING gin (tech_name gin_trgm_ops);

-- 기업-품목 관계 (생산·공급·정비 등)
CREATE TABLE ax.company_item (
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    item_id          bigint NOT NULL REFERENCES ax.item(id) ON DELETE CASCADE,
    relation_type    text NOT NULL DEFAULT 'PRODUCES'
                     CHECK (relation_type IN ('PRODUCES','SUPPLIES','MAINTAINS','DEVELOPS','SIMILAR')),
    since_date       date,
    source_system_code text REFERENCES ax.code_source_system(code),
    PRIMARY KEY (organization_id, item_id, relation_type)
);
CREATE INDEX company_item_item ON ax.company_item(item_id);

-- 수출 유망정보 (품목 또는 기술 단위, 유망 국가·시장)
CREATE TABLE ax.export_prospect (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id          bigint REFERENCES ax.item(id) ON DELETE CASCADE,
    weapon_system_id bigint REFERENCES ax.weapon_system(id) ON DELETE CASCADE,
    tech_taxonomy_id bigint REFERENCES ax.tech_taxonomy(id),
    country_code     char(2),                            -- ISO 3166-1 alpha-2
    market_region    text,
    prospect_level   text CHECK (prospect_level IN ('HIGH','MEDIUM','LOW')),
    description      text,
    reference_year   smallint,
    source_system_code text REFERENCES ax.code_source_system(code),
    created_at       timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(item_id, weapon_system_id, tech_taxonomy_id) >= 1)
);
CREATE INDEX export_prospect_item ON ax.export_prospect(item_id);
