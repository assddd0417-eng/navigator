-- =============================================================================
-- 0006: R&D 과제 (Project Master) 및 과제 간 관계
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.project (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_no         text NOT NULL UNIQUE,              -- 과제 ID (표준 과제번호)
    title              text NOT NULL,
    program_id         bigint REFERENCES ax.program(id),   -- 소속 사업트랙
    lead_org_id        bigint REFERENCES ax.organization(id), -- 주관기관
    department_id      bigint REFERENCES ax.department(id),   -- 과제 담당(소관)부서
    manager_user_id    bigint REFERENCES ax.app_user(id),     -- 연구소 내 과제 담당자
    principal_investigator text,                          -- 연구책임자 (외부인일 수 있어 텍스트)
    status_code        text NOT NULL REFERENCES ax.code_project_status(code),
    dev_stage_code     text REFERENCES ax.code_dev_stage(code),
    start_date         date,
    end_date           date,
    objective          text,                              -- 연구개발 목적·목표
    budget_krw         bigint,
    security_code      text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    source_system_code text NOT NULL DEFAULT 'PMS' REFERENCES ax.code_source_system(code),
    last_synced_at     timestamptz,                       -- 원천 동기화 시점 (최신성)
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX project_program ON ax.project(program_id);
CREATE INDEX project_department ON ax.project(department_id);
CREATE INDEX project_status ON ax.project(status_code);
CREATE INDEX project_title_trgm ON ax.project USING gin (title gin_trgm_ops);
CREATE TRIGGER trg_project_updated BEFORE UPDATE ON ax.project
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 과제 참여기관 (주관/공동/참여/위탁) = 기업-과제 관계 포함
CREATE TABLE ax.project_participant (
    project_id      bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    organization_id bigint NOT NULL REFERENCES ax.organization(id),
    role            text NOT NULL CHECK (role IN ('LEAD','JOINT','PARTICIPANT','CONSIGNED','DEMAND_ORG')),
    PRIMARY KEY (project_id, organization_id, role)
);
CREATE INDEX project_participant_org ON ax.project_participant(organization_id);

-- 과제 관련 인원 (담당자 변경 이력 대응: 기간 보관)
CREATE TABLE ax.project_member (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    user_id     bigint REFERENCES ax.app_user(id),
    person_name text NOT NULL,
    role        text NOT NULL CHECK (role IN ('PI','CO_PI','MANAGER','RESEARCHER','CONTACT')),
    valid_from  date,
    valid_to    date
);
CREATE INDEX project_member_project ON ax.project_member(project_id);

-- 과제 간 관계: 선행·후속·유사·중복. is_actual_relay = 과거 실제 이어달리기 사례
CREATE TABLE ax.project_relation (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_project_id    bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    to_project_id      bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    relation_type      text NOT NULL CHECK (relation_type IN ('PRECEDES','SIMILAR','DUPLICATE','DERIVED')),
    linkage_type_code  text REFERENCES ax.code_linkage_type(code), -- 실제 연계 사례의 연계유형
    is_actual_relay    boolean NOT NULL DEFAULT false,
    verified_by        bigint REFERENCES ax.app_user(id),           -- 전문가 확인
    note               text,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CHECK (from_project_id <> to_project_id),
    UNIQUE (from_project_id, to_project_id, relation_type)
);
CREATE INDEX project_relation_to ON ax.project_relation(to_project_id);
