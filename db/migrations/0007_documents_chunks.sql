-- =============================================================================
-- 0007: 원문 문서·조항·청크 (Source Master, RAG 근거 저장소)
--   source_document  : 출처 문서 (버전·작성일·보안등급·비식별 여부)
--   document_section : 장·절·조항 계층 (예: "제3조", "3.2.1")
--   document_chunk   : 검색·임베딩 단위 텍스트 + 페이지/문단/표/셀 위치
--   evidence         : 특정 원문 위치를 가리키는 근거 단위 (카드 필드·추천이 공통 참조)
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.source_document (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_type_code       text NOT NULL REFERENCES ax.code_document_type(code),
    title               text NOT NULL,
    project_id          bigint REFERENCES ax.project(id) ON DELETE SET NULL,
    program_id          bigint REFERENCES ax.program(id) ON DELETE SET NULL,
    owner_dept_id       bigint REFERENCES ax.department(id),  -- 소관부서 (열람권한 판단)
    source_system_code  text NOT NULL REFERENCES ax.code_source_system(code),
    external_ref        text,                                  -- 원천시스템 문서 ID/URL
    version_label       text,                                  -- 예: 'v1.2', '최종'
    authored_at         date,                                  -- 작성일
    supersedes_id       bigint REFERENCES ax.source_document(id), -- 이전 버전
    is_latest           boolean NOT NULL DEFAULT true,
    storage_uri         text,                                  -- 원본 파일 위치 (오브젝트 스토리지 등)
    mime_type           text,
    file_sha256         char(64),
    page_count          integer,
    language            text NOT NULL DEFAULT 'ko',
    security_code       text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    is_deidentified     boolean NOT NULL DEFAULT false,         -- 비식별/마스킹 처리 여부
    deidentify_note     text,
    parse_status        text NOT NULL DEFAULT 'PENDING'
                        CHECK (parse_status IN ('PENDING','PARSED','CHUNKED','EMBEDDED','FAILED')),
    parse_error         text,
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb,     -- 서지정보(논문), 출원번호(특허) 등
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_system_code, external_ref, version_label)
);
CREATE INDEX source_document_project ON ax.source_document(project_id);
CREATE INDEX source_document_program ON ax.source_document(program_id);
CREATE INDEX source_document_type ON ax.source_document(doc_type_code) WHERE is_latest;
CREATE UNIQUE INDEX source_document_sha ON ax.source_document(file_sha256) WHERE file_sha256 IS NOT NULL;
CREATE TRIGGER trg_source_document_updated BEFORE UPDATE ON ax.source_document
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 장·절·조항 (계층형)
CREATE TABLE ax.document_section (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  bigint NOT NULL REFERENCES ax.source_document(id) ON DELETE CASCADE,
    parent_id    bigint REFERENCES ax.document_section(id) ON DELETE CASCADE,
    section_no   text,                      -- '제3조', '3.2.1', '부록 A'
    heading      text,
    level        smallint NOT NULL DEFAULT 1,
    page_start   integer,
    page_end     integer,
    ordinal      integer NOT NULL,          -- 문서 내 순서
    UNIQUE (document_id, ordinal)
);
CREATE INDEX document_section_parent ON ax.document_section(parent_id);

-- 청크: 검색·임베딩 단위
CREATE TABLE ax.document_chunk (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   bigint NOT NULL REFERENCES ax.source_document(id) ON DELETE CASCADE,
    section_id    bigint REFERENCES ax.document_section(id) ON DELETE SET NULL,
    chunk_index   integer NOT NULL,
    content       text NOT NULL,
    content_sha256 char(64) NOT NULL,
    token_count   integer,
    page_start    integer,
    page_end      integer,
    location      jsonb NOT NULL DEFAULT '{}'::jsonb,
        -- 예: {"paragraph":3,"table":"표 2-1","row":4,"col":2,"bbox":[x0,y0,x1,y1]}
    chunk_type    text NOT NULL DEFAULT 'TEXT' CHECK (chunk_type IN ('TEXT','TABLE','FIGURE_CAPTION','LIST')),
    -- 키워드 검색 (한국어 형태소 사전 미적용: simple + pg_trgm 병행)
    tsv           tsvector GENERATED ALWAYS AS (to_tsvector('simple', content)) STORED,
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (document_id, chunk_index),
    CHECK (page_end IS NULL OR page_start IS NULL OR page_end >= page_start)
);
CREATE INDEX document_chunk_section ON ax.document_chunk(section_id);
CREATE INDEX document_chunk_tsv ON ax.document_chunk USING gin (tsv);
CREATE INDEX document_chunk_trgm ON ax.document_chunk USING gin (content gin_trgm_ops);

-- 근거: 원문 내 특정 위치(인용문). 청크보다 좁은 범위의 인용 가능
CREATE TABLE ax.evidence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   bigint NOT NULL REFERENCES ax.source_document(id) ON DELETE CASCADE,
    section_id    bigint REFERENCES ax.document_section(id) ON DELETE SET NULL,
    chunk_id      bigint REFERENCES ax.document_chunk(id) ON DELETE SET NULL,
    page_start    integer,
    page_end      integer,
    quote         text,                     -- 원문 인용
    location      jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_by    text NOT NULL DEFAULT 'AI' CHECK (created_by IN ('AI','HUMAN','IMPORT')),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX evidence_document ON ax.evidence(document_id);
CREATE INDEX evidence_chunk ON ax.evidence(chunk_id);
COMMENT ON TABLE ax.evidence IS '원문 근거 단위 (출처 문서·조항·페이지·청크·인용문)';

-- 문서 단위 개별 열람 허용 (부서·등급 규칙 외 예외 부여)
CREATE TABLE ax.document_access_grant (
    document_id     bigint NOT NULL REFERENCES ax.source_document(id) ON DELETE CASCADE,
    grantee_user_id bigint NOT NULL REFERENCES ax.app_user(id) ON DELETE CASCADE,
    granted_by      bigint REFERENCES ax.app_user(id),
    valid_to        timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (document_id, grantee_user_id)
);

-- 사업트랙 적용조건 → 근거 (사업공고·규정 조항)
ALTER TABLE ax.program_condition
    ADD COLUMN evidence_id bigint REFERENCES ax.evidence(id) ON DELETE SET NULL;
