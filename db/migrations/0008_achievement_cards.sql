-- =============================================================================
-- 0008: 성과 활용카드 (Achievement Master) 및 성과 관계 그래프
--   카드 1장 = 과제의 대표 성과 1건. 하위 테이블로 핵심기술·성능·미해결 항목·
--   연구성과/지재권·무기체계·품목·기업·사업트랙 관계를 구조화한다.
--   모든 구조화 정보는 card_field_evidence 로 원문 위치와 연결된다.
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.achievement_card (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_no             text NOT NULL UNIQUE,                 -- 예: 'AC-2026-000123'
    project_id          bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    title               text NOT NULL,
    core_achievement    text NOT NULL,                        -- 핵심성과 (대표 성과 요약)
    summary             text,                                 -- 카드 전체 요약 (임베딩 SUMMARY 원천)
    trl                 smallint CHECK (trl BETWEEN 1 AND 9), -- 기술성숙도
    trl_basis           text,                                 -- TRL 판단 근거 요약
    dev_stage_code      text REFERENCES ax.code_dev_stage(code),
    test_conditions     text,                                 -- 시험조건·시험환경 (서술형)
    application_env     text,                                 -- 운용·적용환경
    utilization_assessment jsonb NOT NULL DEFAULT '{}'::jsonb,
        -- 성과 활용 가능성 (유형별 판정+근거) 예: {"FOLLOW_UP":{"level":"HIGH","reason":"..."}}
    has_follow_up_research boolean NOT NULL DEFAULT false,    -- 후속 연구 진행 여부 (최신성)
    latest_utilization_at  date,                              -- 최근 활용실적 일자
    status              text NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT','IN_REVIEW','PUBLISHED','ARCHIVED')),
    revision            integer NOT NULL DEFAULT 1,           -- 갱신 시 +1, 이전 값은 audit_log
    extracted_by        text NOT NULL DEFAULT 'AI' CHECK (extracted_by IN ('AI','HUMAN','IMPORT')),
    extraction_model    text,                                 -- 추출에 사용한 LLM 식별자
    extraction_confidence real CHECK (extraction_confidence BETWEEN 0 AND 1),
    curated_by          bigint REFERENCES ax.app_user(id),    -- 검수 확정자
    curated_at          timestamptz,
    security_code       text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX achievement_card_project ON ax.achievement_card(project_id);
CREATE INDEX achievement_card_status ON ax.achievement_card(status);
CREATE INDEX achievement_card_title_trgm ON ax.achievement_card USING gin (title gin_trgm_ops);
CREATE TRIGGER trg_achievement_card_updated BEFORE UPDATE ON ax.achievement_card
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();
COMMENT ON TABLE ax.achievement_card IS '성과 활용카드';

-- 핵심기술 + 기술원리 (카드당 N개, 대표 1개)
CREATE TABLE ax.card_technology (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id          bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    tech_name        text NOT NULL,                           -- 핵심 기술명
    principle        text,                                    -- 기술원리·핵심 메커니즘
    tech_taxonomy_id bigint REFERENCES ax.tech_taxonomy(id),
    is_primary       boolean NOT NULL DEFAULT false,
    sort_order       smallint NOT NULL DEFAULT 0
);
CREATE INDEX card_technology_card ON ax.card_technology(card_id);
CREATE INDEX card_technology_taxonomy ON ax.card_technology(tech_taxonomy_id);
CREATE UNIQUE INDEX card_technology_one_primary ON ax.card_technology(card_id) WHERE is_primary;

-- 달성성능 (목표 대비 달성/미달성 포함, 정량지표)
CREATE TABLE ax.card_performance (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id         bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    metric_name     text NOT NULL,                            -- 예: '탐지거리'
    comparator      text NOT NULL DEFAULT 'GTE' CHECK (comparator IN ('GTE','LTE','EQ','RANGE')),
    target_value    numeric,                                  -- 목표값
    achieved_value  numeric,                                  -- 달성값
    achieved_text   text,                                     -- 수치화 곤란 시 서술
    unit            text,
    is_achieved     boolean,                                  -- false = 미달성 성과
    test_condition  text,                                     -- 해당 지표의 시험조건
    sort_order      smallint NOT NULL DEFAULT 0
);
CREATE INDEX card_performance_card ON ax.card_performance(card_id);
CREATE INDEX card_performance_metric_trgm ON ax.card_performance USING gin (metric_name gin_trgm_ops);

-- 미해결 기술항목 / 미달성 항목 / 후속 연구 필요사항  → 후속형·고도화형 핵심 입력
CREATE TABLE ax.card_open_issue (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id       bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    issue_type    text NOT NULL CHECK (issue_type IN ('UNRESOLVED_TECH','UNMET_TARGET','FOLLOW_UP_NEED')),
    description   text NOT NULL,
    performance_id bigint REFERENCES ax.card_performance(id) ON DELETE SET NULL, -- 미달성 지표 연결
    priority      text CHECK (priority IN ('HIGH','MEDIUM','LOW')),
    source        text NOT NULL DEFAULT 'AI' CHECK (source IN ('AI','EXPERT','REPORT')),
    is_resolved   boolean NOT NULL DEFAULT false,              -- 후속 과제로 해결되면 true
    resolved_by_project_id bigint REFERENCES ax.project(id),
    sort_order    smallint NOT NULL DEFAULT 0
);
CREATE INDEX card_open_issue_card ON ax.card_open_issue(card_id);
CREATE INDEX card_open_issue_open ON ax.card_open_issue(issue_type) WHERE NOT is_resolved;

-- 주요 연구성과·지식재산권 (논문·특허·기술이전·시험 등)
CREATE TABLE ax.card_outcome (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id         bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    outcome_type_code text NOT NULL REFERENCES ax.code_outcome_type(code),
    title           text NOT NULL,
    identifier      text,                                     -- 특허 출원/등록번호, DOI 등
    outcome_date    date,
    holder          text,                                     -- 권리자
    document_id     bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,
    metadata        jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX card_outcome_card ON ax.card_outcome(card_id);
CREATE INDEX card_outcome_identifier ON ax.card_outcome(identifier) WHERE identifier IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 성과 관계 그래프 (성과-무기체계/품목/기업/사업트랙)
--   relation_status: 불확실한 관계는 NEEDS_CONFIRMATION ('추가 확인 필요')
-- ---------------------------------------------------------------------------
CREATE TABLE ax.card_weapon_system (
    card_id          bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    weapon_system_id bigint NOT NULL REFERENCES ax.weapon_system(id),
    relation_type    text NOT NULL DEFAULT 'APPLIED' CHECK (relation_type IN ('APPLIED','PLANNED','CANDIDATE')),
    relation_status  text NOT NULL DEFAULT 'CONFIRMED' CHECK (relation_status IN ('CONFIRMED','NEEDS_CONFIRMATION','REJECTED')),
    origin           text NOT NULL DEFAULT 'SOURCE' CHECK (origin IN ('SOURCE','AI','HUMAN')),
    confidence       real CHECK (confidence BETWEEN 0 AND 1),
    PRIMARY KEY (card_id, weapon_system_id, relation_type)
);
CREATE INDEX card_weapon_system_ws ON ax.card_weapon_system(weapon_system_id);

CREATE TABLE ax.card_item (
    card_id          bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    item_id          bigint NOT NULL REFERENCES ax.item(id),
    relation_type    text NOT NULL DEFAULT 'APPLIED' CHECK (relation_type IN ('APPLIED','PLANNED','CANDIDATE','LOCALIZATION_TARGET')),
    relation_status  text NOT NULL DEFAULT 'CONFIRMED' CHECK (relation_status IN ('CONFIRMED','NEEDS_CONFIRMATION','REJECTED')),
    origin           text NOT NULL DEFAULT 'SOURCE' CHECK (origin IN ('SOURCE','AI','HUMAN')),
    confidence       real CHECK (confidence BETWEEN 0 AND 1),
    PRIMARY KEY (card_id, item_id, relation_type)
);
CREATE INDEX card_item_item ON ax.card_item(item_id);

CREATE TABLE ax.card_company (
    card_id          bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id),
    relation_type    text NOT NULL CHECK (relation_type IN
                      ('DEVELOPER','TECH_HOLDER','SIMILAR_PRODUCER','TRANSFER_CANDIDATE','TRANSFEREE')),
    relation_status  text NOT NULL DEFAULT 'NEEDS_CONFIRMATION' CHECK (relation_status IN ('CONFIRMED','NEEDS_CONFIRMATION','REJECTED')),
    origin           text NOT NULL DEFAULT 'AI' CHECK (origin IN ('SOURCE','AI','HUMAN')),
    confidence       real CHECK (confidence BETWEEN 0 AND 1),
    PRIMARY KEY (card_id, organization_id, relation_type)
);
CREATE INDEX card_company_org ON ax.card_company(organization_id);

CREATE TABLE ax.card_program (
    card_id          bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    program_id       bigint NOT NULL REFERENCES ax.program(id),
    relation_type    text NOT NULL DEFAULT 'FOLLOW_UP_CANDIDATE'
                     CHECK (relation_type IN ('ORIGIN','FOLLOW_UP_CANDIDATE','LINKED')),
    relation_status  text NOT NULL DEFAULT 'NEEDS_CONFIRMATION' CHECK (relation_status IN ('CONFIRMED','NEEDS_CONFIRMATION','REJECTED')),
    origin           text NOT NULL DEFAULT 'AI' CHECK (origin IN ('SOURCE','AI','HUMAN')),
    confidence       real CHECK (confidence BETWEEN 0 AND 1),
    PRIMARY KEY (card_id, program_id, relation_type)
);
CREATE INDEX card_program_program ON ax.card_program(program_id);

-- ---------------------------------------------------------------------------
-- 카드 필드 ↔ 원문 근거
--   target_table + target_id(단일 PK) 또는 target_key(복합 PK 관계 테이블)로 행을 지정하고
--   field_name 으로 컬럼(예: 'achieved_value')을 지정. 카드 자체 필드면 target_table='achievement_card'
-- ---------------------------------------------------------------------------
CREATE TABLE ax.card_field_evidence (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id      bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    target_table text NOT NULL CHECK (target_table IN
                  ('achievement_card','card_technology','card_performance','card_open_issue',
                   'card_outcome','card_weapon_system','card_item','card_company','card_program')),
    target_id    bigint,                    -- 단일 PK 하위 행의 id
    target_key   jsonb,                     -- 복합 PK 관계 행의 키, 예: {"weapon_system_id":3,"relation_type":"APPLIED"}
    field_name   text NOT NULL,
    evidence_id  bigint NOT NULL REFERENCES ax.evidence(id) ON DELETE CASCADE,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CHECK (target_table = 'achievement_card' OR num_nonnulls(target_id, target_key) = 1)
);
CREATE INDEX card_field_evidence_card ON ax.card_field_evidence(card_id);
CREATE INDEX card_field_evidence_target ON ax.card_field_evidence(target_table, target_id);

-- 카드 원천 문서 (카드 생성에 사용된 문서 목록)
CREATE TABLE ax.card_source_document (
    card_id     bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    document_id bigint NOT NULL REFERENCES ax.source_document(id) ON DELETE CASCADE,
    PRIMARY KEY (card_id, document_id)
);
