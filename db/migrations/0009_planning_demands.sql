-- =============================================================================
-- 0009: 신규 기획수요 (Demand Master)
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.planning_demand (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_no           text NOT NULL UNIQUE,              -- 신규 과제 수요 ID
    title               text NOT NULL,                     -- 신규 과제명/가제
    tech_need           text NOT NULL,                     -- 기술수요: 필요 기술·해결하려는 문제
    business_purpose    text,                              -- 사업목적·정책목표
    application_env     text,                              -- 운용·시험 적용환경
    required_trl_min    smallint CHECK (required_trl_min BETWEEN 1 AND 9),
    required_trl_max    smallint CHECK (required_trl_max BETWEEN 1 AND 9),
    dev_stage_code      text REFERENCES ax.code_dev_stage(code),
    target_program_id   bigint REFERENCES ax.program(id),  -- 추진 예정 사업트랙
    requesting_dept_id  bigint REFERENCES ax.department(id),
    owner_user_id       bigint REFERENCES ax.app_user(id), -- 기획 담당자
    status              text NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT','OPEN','MATCHING','IN_REVIEW','PLANNED','CLOSED')),
    security_code       text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    source_document_id  bigint REFERENCES ax.source_document(id) ON DELETE SET NULL, -- 기획자료 원문
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (required_trl_min IS NULL OR required_trl_max IS NULL OR required_trl_min <= required_trl_max)
);
CREATE INDEX planning_demand_status ON ax.planning_demand(status);
CREATE INDEX planning_demand_title_trgm ON ax.planning_demand USING gin (title gin_trgm_ops);
CREATE TRIGGER trg_planning_demand_updated BEFORE UPDATE ON ax.planning_demand
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 요구성능 (정량)
CREATE TABLE ax.demand_performance_req (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id      bigint NOT NULL REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    metric_name    text NOT NULL,
    comparator     text NOT NULL DEFAULT 'GTE' CHECK (comparator IN ('GTE','LTE','EQ','RANGE')),
    required_value numeric,
    required_max   numeric,                      -- RANGE 일 때 상한
    required_text  text,
    unit           text,
    is_mandatory   boolean NOT NULL DEFAULT true,
    sort_order     smallint NOT NULL DEFAULT 0
);
CREATE INDEX demand_performance_req_demand ON ax.demand_performance_req(demand_id);

CREATE TABLE ax.demand_weapon_system (
    demand_id        bigint NOT NULL REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    weapon_system_id bigint NOT NULL REFERENCES ax.weapon_system(id),
    PRIMARY KEY (demand_id, weapon_system_id)
);

CREATE TABLE ax.demand_item (
    demand_id bigint NOT NULL REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    item_id   bigint NOT NULL REFERENCES ax.item(id),
    PRIMARY KEY (demand_id, item_id)
);

CREATE TABLE ax.demand_technology (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id        bigint NOT NULL REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    tech_name        text NOT NULL,                -- 수요 기술요소 (융합형 판정 시 요소별 충족 분석)
    description      text,
    tech_taxonomy_id bigint REFERENCES ax.tech_taxonomy(id)
);
CREATE INDEX demand_technology_demand ON ax.demand_technology(demand_id);
