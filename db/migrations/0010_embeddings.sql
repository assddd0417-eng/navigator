-- =============================================================================
-- 0010: 임베딩 저장 및 벡터 인덱스 (pgvector)
--   가정: 임베딩 차원 1024 (예: BGE-M3, multilingual-e5-large 등 폐쇄망 구동 가능 다국어 모델)
--         거리척도 cosine (vector_cosine_ops). 정규화 벡터 사용 시 inner product 로 교체 가능.
--   차원이 다른 모델로 교체 시: 새 마이그레이션에서 컬럼 타입 변경 + 재임베딩 + 인덱스 재생성.
--
--   패싯(facet) 임베딩: 하나의 카드/수요를 관점별로 나누어 임베딩한다.
--     카드  : SUMMARY, CORE_TECH, PRINCIPLE, PERFORMANCE, OPEN_ISSUE, APPLICATION_ENV
--     수요  : SUMMARY, TECH_NEED, PERFORMANCE, APPLICATION_ENV, PURPOSE
--   패싯별 부분(partial) HNSW 인덱스를 두어, WHERE facet = '...' 조건에서도 인덱스가
--   필터 없이 동작하도록 한다 (필터 후 결과 부족 문제 회피).
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.embedding_model (
    id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,                   -- 예: 'BAAI/bge-m3'
    version     text NOT NULL DEFAULT '1',
    dimension   integer NOT NULL CHECK (dimension = 1024), -- 현재 스키마 고정 차원
    distance    text NOT NULL DEFAULT 'cosine' CHECK (distance IN ('cosine','ip','l2')),
    is_active   boolean NOT NULL DEFAULT false,
    note        text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (name, version)
);
CREATE UNIQUE INDEX embedding_model_one_active ON ax.embedding_model((true)) WHERE is_active;

INSERT INTO ax.embedding_model (name, version, dimension, distance, is_active, note)
VALUES ('BAAI/bge-m3', '1', 1024, 'cosine', true, '가정값: 실제 채택 모델로 교체');

-- 문서 청크 임베딩 (RAG 근거 검색)
CREATE TABLE ax.chunk_embedding (
    chunk_id     bigint NOT NULL REFERENCES ax.document_chunk(id) ON DELETE CASCADE,
    model_id     smallint NOT NULL REFERENCES ax.embedding_model(id),
    embedding    vector(1024) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (chunk_id, model_id)
);

-- 성과 활용카드 패싯 임베딩
CREATE TABLE ax.card_embedding (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id      bigint NOT NULL REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    facet        text NOT NULL CHECK (facet IN
                  ('SUMMARY','CORE_TECH','PRINCIPLE','PERFORMANCE','OPEN_ISSUE','APPLICATION_ENV')),
    source_table text,                           -- 하위 행 단위 임베딩 시 (예: 'card_open_issue')
    source_id    bigint,
    model_id     smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_text  text NOT NULL,                  -- 임베딩한 원문 (재현·디버깅)
    source_sha256 char(64) NOT NULL,             -- 내용 변경 감지 → 재임베딩 판단
    card_revision integer NOT NULL,              -- 임베딩 시점 카드 revision
    embedding    vector(1024) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (card_id, facet, source_table, source_id, model_id)
);
CREATE INDEX card_embedding_card ON ax.card_embedding(card_id);

-- 신규 기획수요 패싯 임베딩
CREATE TABLE ax.demand_embedding (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id    bigint NOT NULL REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    facet        text NOT NULL CHECK (facet IN ('SUMMARY','TECH_NEED','PERFORMANCE','APPLICATION_ENV','PURPOSE')),
    source_table text,                           -- 예: 'demand_technology' (기술요소별)
    source_id    bigint,
    model_id     smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_text  text NOT NULL,
    source_sha256 char(64) NOT NULL,
    embedding    vector(1024) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (demand_id, facet, source_table, source_id, model_id)
);
CREATE INDEX demand_embedding_demand ON ax.demand_embedding(demand_id);

-- 기업 보유기술 임베딩 (사업화형: 기술-기업 매칭)
CREATE TABLE ax.company_tech_embedding (
    company_technology_id bigint NOT NULL REFERENCES ax.company_technology(id) ON DELETE CASCADE,
    model_id     smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_sha256 char(64) NOT NULL,
    embedding    vector(1024) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (company_technology_id, model_id)
);

-- 사업트랙 목적 임베딩 (사업목적 적합도). 건수가 적어 인덱스 없이 전수 비교
CREATE TABLE ax.program_embedding (
    program_id   bigint NOT NULL REFERENCES ax.program(id) ON DELETE CASCADE,
    model_id     smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_sha256 char(64) NOT NULL,
    embedding    vector(1024) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (program_id, model_id)
);

-- ---------------------------------------------------------------------------
-- HNSW 인덱스 (기본). m=16, ef_construction=64 는 pgvector 기본값.
-- 조회 시 세션에서 `SET hnsw.ef_search = 100;` 등으로 재현율 조정.
-- IVFFlat 대안은 db/optional/ivfflat_indexes.sql 참조.
-- ---------------------------------------------------------------------------
CREATE INDEX chunk_embedding_hnsw ON ax.chunk_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);

CREATE INDEX card_embedding_hnsw_summary ON ax.card_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'SUMMARY';
CREATE INDEX card_embedding_hnsw_core_tech ON ax.card_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'CORE_TECH';
CREATE INDEX card_embedding_hnsw_principle ON ax.card_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'PRINCIPLE';
CREATE INDEX card_embedding_hnsw_open_issue ON ax.card_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'OPEN_ISSUE';
CREATE INDEX card_embedding_hnsw_app_env ON ax.card_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'APPLICATION_ENV';
CREATE INDEX card_embedding_hnsw_performance ON ax.card_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'PERFORMANCE';

-- 수요 → 카드 역방향 탐색 (성과 기점 "이 성과를 쓸 수요는?") 용
