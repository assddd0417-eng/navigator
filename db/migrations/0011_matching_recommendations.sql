-- =============================================================================
-- 0011: 유사도 매칭 실행 및 추천 결과 (AI Recommendation)
--   match_run          : 매칭 1회 실행 (입력·모델·규칙 스냅샷 보관 → 재현성)
--   recommendation     : 연계 후보 1건 (연계유형·순위·종합점수·연계이유·개발필요사항)
--   recommendation_*   : 출처 성과카드(융합형은 2개 이상), 기준별 점수, 유형 분류 확률,
--                        RAG 근거, 담당/협업부서·기업·품목 후보
--   confirmation_item  : 불확실한 관계의 '추가 확인 필요사항'
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.match_run (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_type       text NOT NULL CHECK (run_type IN
                    ('DEMAND_TO_CARD',     -- 신규 수요 기점: 연계 가능한 기존 성과 탐색
                     'CARD_TO_DEMAND',     -- 성과 기점: 활용 가능한 수요 탐색
                     'CARD_TO_PROGRAM',    -- 종료과제 활용후보: 후속 가능 사업트랙 탐색
                     'CARD_TO_COMPANY',    -- 사업화 후보 기업·품목 탐색
                     'BATCH_SCAN',         -- 정기 일괄 점검
                     'EVALUATION')),       -- PoC 검증용 재실행
    demand_id      bigint REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    card_id        bigint REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    model_id       smallint NOT NULL REFERENCES ax.embedding_model(id),
    llm_model      text,                                  -- 유형분류·근거생성 LLM 식별자
    rule_snapshot  jsonb NOT NULL,                        -- 실행 시점 linkage_rule 가중치/조건 복사본
    params         jsonb NOT NULL DEFAULT '{}'::jsonb,    -- {"top_k":20,"ef_search":100,"facets":[...]}
    requested_by   bigint REFERENCES ax.app_user(id),
    status         text NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','CANCELLED')),
    started_at     timestamptz,
    finished_at    timestamptz,
    error_message  text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CHECK (run_type NOT IN ('DEMAND_TO_CARD') OR demand_id IS NOT NULL),
    CHECK (run_type NOT IN ('CARD_TO_DEMAND','CARD_TO_PROGRAM','CARD_TO_COMPANY') OR card_id IS NOT NULL)
);
CREATE INDEX match_run_demand ON ax.match_run(demand_id);
CREATE INDEX match_run_card ON ax.match_run(card_id);

CREATE TABLE ax.recommendation (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_run_id         bigint NOT NULL REFERENCES ax.match_run(id) ON DELETE CASCADE,
    -- 연계 대상 (하나 이상): 신규 수요 / 사업트랙 / 진행 중인 타 부서·타 사업 과제
    demand_id            bigint REFERENCES ax.planning_demand(id) ON DELETE CASCADE,
    target_program_id    bigint REFERENCES ax.program(id),
    target_project_id    bigint REFERENCES ax.project(id),
    linkage_type_code    text NOT NULL REFERENCES ax.code_linkage_type(code), -- AI 판정 대표 유형
    rank                 integer NOT NULL CHECK (rank >= 1),
    total_score          numeric(6,5) NOT NULL CHECK (total_score BETWEEN 0 AND 1), -- 연계 종합점수
    confidence           numeric(6,5) CHECK (confidence BETWEEN 0 AND 1),
    rationale            text NOT NULL,           -- 연계이유 (추천 근거 요약)
    development_needs    text,                    -- 개발필요사항
    is_excluded          boolean NOT NULL DEFAULT false, -- AI 비추천/제외 후보 (검토 효율화용으로 보존)
    exclusion_reason     text,
    status               text NOT NULL DEFAULT 'GENERATED' CHECK (status IN
                          ('GENERATED','ASSIGNED','IN_REVIEW','NEEDS_INFO','DECIDED','WITHDRAWN')),
    -- 최종판정 결과 (review_decision 에서 트리거로 반영, 조회 편의용 비정규화)
    final_decision_code  text REFERENCES ax.code_review_decision(code),
    final_linkage_type_code text REFERENCES ax.code_linkage_type(code),
    final_decided_at     timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(demand_id, target_program_id, target_project_id) >= 1),
    CHECK (NOT is_excluded OR exclusion_reason IS NOT NULL),
    UNIQUE (match_run_id, rank)
);
CREATE INDEX recommendation_demand ON ax.recommendation(demand_id);
CREATE INDEX recommendation_status ON ax.recommendation(status);
CREATE INDEX recommendation_linkage ON ax.recommendation(linkage_type_code);
CREATE TRIGGER trg_recommendation_updated BEFORE UPDATE ON ax.recommendation
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 출처 성과카드 (융합형은 2개 이상)
CREATE TABLE ax.recommendation_source_card (
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    card_id           bigint NOT NULL REFERENCES ax.achievement_card(id),
    role              text NOT NULL DEFAULT 'PRIMARY' CHECK (role IN ('PRIMARY','COMPLEMENTARY')),
    contribution      text,                      -- 융합 시 이 성과가 기여하는 기술요소
    open_issue_id     bigint REFERENCES ax.card_open_issue(id), -- 후속형: 이어갈 미해결 기술
    PRIMARY KEY (recommendation_id, card_id)
);
CREATE INDEX recommendation_source_card_card ON ax.recommendation_source_card(card_id);

-- 기준별 점수 (기술 유사도·성능·TRL·적용환경·사업목적 적합도)
CREATE TABLE ax.recommendation_score (
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    criterion         text NOT NULL CHECK (criterion IN ('TECH','PERFORMANCE','TRL','ENVIRONMENT','PURPOSE')),
    score             numeric(6,5) NOT NULL CHECK (score BETWEEN 0 AND 1),
    weight            numeric(6,5) NOT NULL CHECK (weight BETWEEN 0 AND 1),
    method            text NOT NULL,             -- 'cosine:CORE_TECH↔TECH_NEED', 'rule:trl_gap', 'llm' 등
    detail            jsonb NOT NULL DEFAULT '{}'::jsonb, -- 예: {"raw_cosine":0.82,"matched_facets":[...]}
    PRIMARY KEY (recommendation_id, criterion)
);

-- 6대 연계유형 분류 확률 분포 (대표 유형 외 차순위 유형 검토용)
CREATE TABLE ax.recommendation_linkage_score (
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    linkage_type_code text NOT NULL REFERENCES ax.code_linkage_type(code),
    probability       numeric(6,5) NOT NULL CHECK (probability BETWEEN 0 AND 1),
    reason            text,
    PRIMARY KEY (recommendation_id, linkage_type_code)
);

-- RAG 근거 (출처 문서·조항·페이지·청크는 evidence 가 보유)
CREATE TABLE ax.recommendation_evidence (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    evidence_id       bigint NOT NULL REFERENCES ax.evidence(id),
    side              text NOT NULL CHECK (side IN ('SOURCE_CARD','DEMAND','PROGRAM','COMPANY','ITEM','OTHER')),
    role              text NOT NULL DEFAULT 'SUPPORT' CHECK (role IN ('SUPPORT','CONTRAST','CONDITION','EXCLUSION')),
    criterion         text CHECK (criterion IN ('TECH','PERFORMANCE','TRL','ENVIRONMENT','PURPOSE')),
    relevance_score   numeric(6,5) CHECK (relevance_score BETWEEN 0 AND 1), -- 검색 유사도/리랭크 점수
    explanation       text,                       -- 이 근거가 뒷받침하는 내용
    retrieved_by      text NOT NULL DEFAULT 'RAG' CHECK (retrieved_by IN ('RAG','CARD_FIELD','KEYWORD','HUMAN')),
    sort_order        smallint NOT NULL DEFAULT 0,
    UNIQUE (recommendation_id, evidence_id, side)
);
CREATE INDEX recommendation_evidence_rec ON ax.recommendation_evidence(recommendation_id);

-- 담당부서·협업부서 후보
CREATE TABLE ax.recommendation_department (
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    department_id     bigint NOT NULL REFERENCES ax.department(id),
    role              text NOT NULL CHECK (role IN ('OWNER','COLLABORATOR')),
    confidence        numeric(6,5) CHECK (confidence BETWEEN 0 AND 1),
    reason            text,
    PRIMARY KEY (recommendation_id, department_id)
);
-- 소관(OWNER) 부서 후보는 추천당 1개
CREATE UNIQUE INDEX recommendation_department_one_owner
    ON ax.recommendation_department(recommendation_id) WHERE role = 'OWNER';

-- 기업 후보 (사업화형 등). 자동 선정이 아닌 "관련성 있는 후보"
CREATE TABLE ax.recommendation_company (
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    organization_id   bigint NOT NULL REFERENCES ax.organization(id),
    role              text NOT NULL CHECK (role IN ('TECH_HOLDER','SIMILAR_PRODUCER','SUPPLY_CHAIN','EXPORT_PARTNER')),
    score             numeric(6,5) CHECK (score BETWEEN 0 AND 1),
    reason            text,
    relation_status   text NOT NULL DEFAULT 'NEEDS_CONFIRMATION' CHECK (relation_status IN ('CONFIRMED','NEEDS_CONFIRMATION','REJECTED')),
    PRIMARY KEY (recommendation_id, organization_id, role)
);

-- 품목 후보 (부품국산화·공급망·수출)
CREATE TABLE ax.recommendation_item (
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    item_id           bigint NOT NULL REFERENCES ax.item(id),
    role              text NOT NULL CHECK (role IN ('LOCALIZATION','APPLICATION','SUPPLY_CHAIN','EXPORT')),
    export_prospect_id bigint REFERENCES ax.export_prospect(id),
    reason            text,
    relation_status   text NOT NULL DEFAULT 'NEEDS_CONFIRMATION' CHECK (relation_status IN ('CONFIRMED','NEEDS_CONFIRMATION','REJECTED')),
    PRIMARY KEY (recommendation_id, item_id, role)
);

-- 추가 확인 필요사항 (불확실한 기업·품목·기술 관계)
CREATE TABLE ax.confirmation_item (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    card_id           bigint REFERENCES ax.achievement_card(id) ON DELETE CASCADE,
    subject_type      text NOT NULL CHECK (subject_type IN ('COMPANY','ITEM','TECH','WEAPON_SYSTEM','PROGRAM','PERFORMANCE','OTHER')),
    description       text NOT NULL,
    status            text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED','DISMISSED')),
    assignee_user_id  bigint REFERENCES ax.app_user(id),
    resolved_by       bigint REFERENCES ax.app_user(id),
    resolved_at       timestamptz,
    resolution_note   text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(recommendation_id, card_id) >= 1),
    CHECK (status = 'OPEN' OR resolved_at IS NOT NULL)
);
CREATE INDEX confirmation_item_open ON ax.confirmation_item(recommendation_id) WHERE status = 'OPEN';

-- ---------------------------------------------------------------------------
-- 검토 진입 가드: 추천이 검토 단계(ASSIGNED 이후)로 넘어가려면
--   (1) 원문 근거가 1건 이상 연결되어 있어야 하고 (근거 연결률 100% 목표)
--   (2) 출처 성과카드 수가 연계유형 최소치 이상이어야 한다 (융합형 ≥ 2)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION ax.guard_recommendation_review_entry() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_min   smallint;
    v_cards integer;
    v_evid  integer;
BEGIN
    IF OLD.status = 'GENERATED' AND NEW.status IN ('ASSIGNED','IN_REVIEW','DECIDED') THEN
        SELECT min_source_cards INTO v_min FROM ax.code_linkage_type WHERE code = NEW.linkage_type_code;
        SELECT count(*) INTO v_cards FROM ax.recommendation_source_card WHERE recommendation_id = NEW.id;
        SELECT count(*) INTO v_evid  FROM ax.recommendation_evidence    WHERE recommendation_id = NEW.id;
        IF v_cards < v_min THEN
            RAISE EXCEPTION '추천 %: 연계유형 % 은(는) 출처 성과카드 % 개 이상 필요 (현재 %)',
                NEW.id, NEW.linkage_type_code, v_min, v_cards USING ERRCODE = 'check_violation';
        END IF;
        IF v_evid = 0 THEN
            RAISE EXCEPTION '추천 %: 원문 근거가 연결되지 않아 검토로 넘길 수 없음', NEW.id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_recommendation_review_entry BEFORE UPDATE OF status ON ax.recommendation
    FOR EACH ROW EXECUTE FUNCTION ax.guard_recommendation_review_entry();
