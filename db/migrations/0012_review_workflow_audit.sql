-- 추가 전용 보호. 단, 상위 행 삭제에 따른 FK CASCADE 삭제(트리거 깊이 > 1)는 허용한다.
-- (PoC 재실행으로 match_run 을 지우는 경우 등. 삭제된 내용은 audit_log 에 남는다)
CREATE OR REPLACE FUNCTION ax.forbid_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 AND TG_TABLE_NAME <> 'audit_log' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION '% 은(는) 추가 전용 테이블입니다 (% 불가)', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'insufficient_privilege';
END $$;

CREATE TRIGGER trg_review_decision_append_only BEFORE UPDATE OR DELETE ON ax.review_decision
    FOR EACH ROW EXECUTE FUNCTION ax.forbid_mutation();
CREATE TRIGGER trg_status_history_append_only BEFORE UPDATE OR DELETE ON ax.recommendation_status_history
    FOR EACH ROW EXECUTE FUNCTION ax.forbid_mutation();
CREATE TRIGGER trg_audit_log_append_only BEFORE UPDATE OR DELETE ON ax.audit_log
    FOR EACH ROW EXECUTE FUNCTION ax.forbid_mutation();

-- 범용 감사 트리거. TG_ARGV = PK 컬럼명 목록 (기본 'id')
CREATE OR REPLACE FUNCTION ax.audit_row() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_old  jsonb := CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) END;
    v_new  jsonb := CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) END;
    v_row  jsonb := COALESCE(v_new, v_old);
    v_pk   jsonb := '{}'::jsonb;
    v_col  text;
    v_changed text[];
BEGIN
    IF TG_NARGS = 0 THEN
        v_pk := jsonb_build_object('id', v_row -> 'id');
    ELSE
        FOREACH v_col IN ARRAY TG_ARGV LOOP
            v_pk := v_pk || jsonb_build_object(v_col, v_row -> v_col);
        END LOOP;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        SELECT array_agg(n.key ORDER BY n.key) INTO v_changed
        FROM jsonb_each(v_new) n
        WHERE n.key <> 'updated_at' AND n.value IS DISTINCT FROM v_old -> n.key;
        IF v_changed IS NULL THEN
            RETURN NULL;                 -- 실질 변경 없음
        END IF;
    END IF;

    INSERT INTO ax.audit_log (actor_user_id, request_id, table_name, row_pk, action, old_data, new_data, changed_fields)
    VALUES (ax.current_app_user(), ax.current_request_id(), TG_TABLE_NAME, v_pk,
            left(TG_OP, 1), v_old, v_new, v_changed);
    RETURN NULL;
END $$;

