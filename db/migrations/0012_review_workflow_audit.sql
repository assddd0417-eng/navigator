-- =============================================================================
-- 0012: Human-in-the-Loop 검토 워크플로우, 검토 이력, 감사 로그
--   흐름: recommendation(GENERATED)
--         → review_assignment 생성 (담당부서/전문가 배정)        status: ASSIGNED
--         → 검토자 의견 review_decision(is_final=false)          status: IN_REVIEW / NEEDS_INFO
--         → 담당부서 최종판정 review_decision(is_final=true)     status: DECIDED
--   원칙: AI 는 후보·근거만 제시하고 최종판정은 반드시 사람(DEPT_REVIEWER/ADMIN)이 한다.
--   review_decision, recommendation_status_history, audit_log 는 추가 전용(append-only).
-- =============================================================================
SET search_path = ax, public;

-- 검토 배정
CREATE TABLE ax.review_assignment (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    review_role       text NOT NULL CHECK (review_role IN ('DEPT_OWNER','COLLAB_DEPT','EXPERT')),
    assignee_user_id  bigint REFERENCES ax.app_user(id),
    assignee_dept_id  bigint REFERENCES ax.department(id),
    status            text NOT NULL DEFAULT 'PENDING'
                      CHECK (status IN ('PENDING','IN_PROGRESS','SUBMITTED','DECLINED','CANCELLED')),
    assigned_by       bigint REFERENCES ax.app_user(id),
    assigned_at       timestamptz NOT NULL DEFAULT now(),
    due_at            timestamptz,
    completed_at      timestamptz,
    note              text,
    CHECK (num_nonnulls(assignee_user_id, assignee_dept_id) >= 1)
);
CREATE INDEX review_assignment_rec ON ax.review_assignment(recommendation_id);
CREATE INDEX review_assignment_user_open ON ax.review_assignment(assignee_user_id)
    WHERE status IN ('PENDING','IN_PROGRESS');
CREATE INDEX review_assignment_dept_open ON ax.review_assignment(assignee_dept_id)
    WHERE status IN ('PENDING','IN_PROGRESS');

-- 검토 의견·판정 (추가 전용). 재판정은 새 행으로 기록
CREATE TABLE ax.review_decision (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id     bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    assignment_id         bigint REFERENCES ax.review_assignment(id),
    reviewer_id           bigint NOT NULL REFERENCES ax.app_user(id),
    decision_code         text NOT NULL REFERENCES ax.code_review_decision(code),
    is_final              boolean NOT NULL DEFAULT false,        -- 담당부서 최종판정
    linkage_type_override text REFERENCES ax.code_linkage_type(code), -- 전문가가 연계유형 수정
    opinion               text,
    -- PoC 품질 평가 항목 (전문가 검증)
    relevance_rating      smallint CHECK (relevance_rating BETWEEN 1 AND 5),   -- 관련성
    is_low_relevance      boolean,                                             -- 관련성 낮은 후보
    evidence_adequacy     smallint CHECK (evidence_adequacy BETWEEN 1 AND 5),  -- 추천근거 적절성
    dev_needs_accuracy    text CHECK (dev_needs_accuracy IN ('CORRECT','PARTIAL','INCORRECT')), -- 개발필요사항 정확성
    supersedes_id         bigint REFERENCES ax.review_decision(id),
    created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX review_decision_rec ON ax.review_decision(recommendation_id, created_at DESC);

-- 검토 토론 (선택)
CREATE TABLE ax.review_comment (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    parent_id         bigint REFERENCES ax.review_comment(id) ON DELETE CASCADE,
    author_id         bigint NOT NULL REFERENCES ax.app_user(id),
    body              text NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    edited_at         timestamptz
);
CREATE INDEX review_comment_rec ON ax.review_comment(recommendation_id);

-- 추천 상태 변경 이력 (검토 이력 조회용 정형 로그)
CREATE TABLE ax.recommendation_status_history (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id) ON DELETE CASCADE,
    from_status       text,
    to_status         text NOT NULL,
    changed_by        bigint REFERENCES ax.app_user(id),
    reason            text,
    changed_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX recommendation_status_history_rec ON ax.recommendation_status_history(recommendation_id, changed_at);

-- 범용 감사 로그 (행 단위 변경 전/후)
CREATE TABLE ax.audit_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    actor_user_id  bigint,                      -- FK 미설정: 사용자 삭제 후에도 로그 보존
    request_id     text,
    db_user        text NOT NULL DEFAULT current_user,
    table_name     text NOT NULL,
    row_pk         jsonb NOT NULL,
    action         char(1) NOT NULL CHECK (action IN ('I','U','D')),
    old_data       jsonb,
    new_data       jsonb,
    changed_fields text[]
);
CREATE INDEX audit_log_table_pk ON ax.audit_log(table_name, row_pk);
CREATE INDEX audit_log_actor ON ax.audit_log(actor_user_id, occurred_at DESC);
CREATE INDEX audit_log_time ON ax.audit_log USING brin (occurred_at);

