-- 추천 상태 변경 → 상태 이력 기록
CREATE OR REPLACE FUNCTION ax.log_recommendation_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO ax.recommendation_status_history (recommendation_id, from_status, to_status, changed_by)
        VALUES (NEW.id, NULL, NEW.status, ax.current_app_user());
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO ax.recommendation_status_history (recommendation_id, from_status, to_status, changed_by, reason)
        VALUES (NEW.id, OLD.status, NEW.status, ax.current_app_user(),
                NULLIF(current_setting('app.status_reason', true), ''));
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_recommendation_status_history AFTER INSERT OR UPDATE OF status ON ax.recommendation
    FOR EACH ROW EXECUTE FUNCTION ax.log_recommendation_status();

-- 검토 배정 생성 → 추천 상태 ASSIGNED
CREATE OR REPLACE FUNCTION ax.on_review_assigned() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE ax.recommendation SET status = 'ASSIGNED'
    WHERE id = NEW.recommendation_id AND status = 'GENERATED';
    RETURN NULL;
END $$;

CREATE TRIGGER trg_review_assignment_created AFTER INSERT ON ax.review_assignment
    FOR EACH ROW EXECUTE FUNCTION ax.on_review_assigned();

-- 판정 입력 검증: 최종판정은 사람(DEPT_REVIEWER/ADMIN)만, 최종 가능한 판정코드만
CREATE OR REPLACE FUNCTION ax.validate_review_decision() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_status text;
BEGIN
    SELECT status INTO v_status FROM ax.recommendation WHERE id = NEW.recommendation_id;
    IF v_status IN ('GENERATED','WITHDRAWN') THEN
        RAISE EXCEPTION '추천 % 은(는) 검토 배정 전이거나 철회된 상태(%)입니다', NEW.recommendation_id, v_status
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.is_final THEN
        IF NOT EXISTS (SELECT 1 FROM ax.code_review_decision WHERE code = NEW.decision_code AND is_terminal) THEN
            RAISE EXCEPTION '판정 % 은(는) 최종판정으로 사용할 수 없습니다', NEW.decision_code
                USING ERRCODE = 'check_violation';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM ax.user_role
                       WHERE user_id = NEW.reviewer_id AND role_code IN ('DEPT_REVIEWER','ADMIN')) THEN
            RAISE EXCEPTION '사용자 % 은(는) 최종판정 권한(DEPT_REVIEWER)이 없습니다', NEW.reviewer_id
                USING ERRCODE = 'insufficient_privilege';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_review_decision_validate BEFORE INSERT ON ax.review_decision
    FOR EACH ROW EXECUTE FUNCTION ax.validate_review_decision();

-- 판정 반영: 배정 완료 처리, 추천 상태·최종판정 비정규화 컬럼 갱신
CREATE OR REPLACE FUNCTION ax.apply_review_decision() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.assignment_id IS NOT NULL THEN
        UPDATE ax.review_assignment
           SET status = 'SUBMITTED', completed_at = NEW.created_at
         WHERE id = NEW.assignment_id AND status IN ('PENDING','IN_PROGRESS');
    END IF;

    IF NEW.is_final THEN
        UPDATE ax.recommendation r
           SET status = 'DECIDED',
               final_decision_code = NEW.decision_code,
               final_linkage_type_code = COALESCE(NEW.linkage_type_override, r.linkage_type_code),
               final_decided_at = NEW.created_at
         WHERE r.id = NEW.recommendation_id;
    ELSIF NEW.decision_code = 'NEEDS_INFO' THEN
        UPDATE ax.recommendation SET status = 'NEEDS_INFO'
         WHERE id = NEW.recommendation_id AND status <> 'DECIDED';
    ELSE
        UPDATE ax.recommendation SET status = 'IN_REVIEW'
         WHERE id = NEW.recommendation_id AND status IN ('ASSIGNED','NEEDS_INFO');
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_review_decision_apply AFTER INSERT ON ax.review_decision
    FOR EACH ROW EXECUTE FUNCTION ax.apply_review_decision();
