SET search_path = ax, public;

-- 통합기획 회의
CREATE TABLE ax.planning_meeting (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           text NOT NULL,
    held_at         timestamptz,
    host_dept_id    bigint REFERENCES ax.department(id),
    status          text NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','HELD','CANCELLED')),
    minutes_document_id bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,
    created_by      bigint REFERENCES ax.app_user(id),
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ax.planning_meeting_department (
    meeting_id    bigint NOT NULL REFERENCES ax.planning_meeting(id) ON DELETE CASCADE,
    department_id bigint NOT NULL REFERENCES ax.department(id),
    PRIMARY KEY (meeting_id, department_id)
);

-- 이어달리기 후보 검토표 (부서별 자동 생성)
CREATE TABLE ax.relay_review_sheet (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           text NOT NULL,
    department_id   bigint REFERENCES ax.department(id),   -- 대상 부서 (NULL = 전사)
    meeting_id      bigint REFERENCES ax.planning_meeting(id) ON DELETE SET NULL,
    sheet_scope     text NOT NULL CHECK (sheet_scope IN
                     ('COMPLETED_PROJECT_UTILIZATION',  -- 종료과제 활용후보
                      'CROSS_PROGRAM',                  -- 사업트랙 간 연계 가능 후보
                      'DEMAND',                         -- 특정 신규수요 대상
                      'CUSTOM')),
    demand_id       bigint REFERENCES ax.planning_demand(id) ON DELETE SET NULL,
    status          text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','FINALIZED','ARCHIVED')),
    generated_by    text NOT NULL DEFAULT 'AI' CHECK (generated_by IN ('AI','HUMAN')),
    export_document_id bigint REFERENCES ax.source_document(id) ON DELETE SET NULL, -- XLSX/HWPX 산출물
    created_by      bigint REFERENCES ax.app_user(id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_relay_review_sheet_updated BEFORE UPDATE ON ax.relay_review_sheet
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

CREATE TABLE ax.relay_review_sheet_item (
    sheet_id          bigint NOT NULL REFERENCES ax.relay_review_sheet(id) ON DELETE CASCADE,
    recommendation_id bigint NOT NULL REFERENCES ax.recommendation(id),
    sort_order        integer NOT NULL,
    snapshot          jsonb NOT NULL,  -- 생성 시점 후보·연계유형·근거·담당부서·판정 스냅샷 (회의자료 재현)
    PRIMARY KEY (sheet_id, recommendation_id)
);

-- 통합기획 자료 초안 (LLM 생성, 버전 관리)
CREATE TABLE ax.planning_draft (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id        bigint REFERENCES ax.relay_review_sheet(id) ON DELETE SET NULL,
    demand_id       bigint REFERENCES ax.planning_demand(id) ON DELETE SET NULL,
    title           text NOT NULL,
    version         integer NOT NULL DEFAULT 1,
    content_md      text NOT NULL,                       -- 초안 본문 (Markdown)
    content_struct  jsonb NOT NULL DEFAULT '{}'::jsonb,  -- 구조화 섹션 (배경/후보/연계유형/개발필요사항/근거)
    generated_by    text NOT NULL DEFAULT 'AI' CHECK (generated_by IN ('AI','HUMAN')),
    llm_model       text,
    status          text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','REVIEWED','FINAL')),
    export_document_id bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,
    created_by      bigint REFERENCES ax.app_user(id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(sheet_id, demand_id) >= 1)
);

-- 초안이 인용한 근거 (초안 내 각주 ↔ 원문)
CREATE TABLE ax.planning_draft_evidence (
    draft_id     bigint NOT NULL REFERENCES ax.planning_draft(id) ON DELETE CASCADE,
    evidence_id  bigint NOT NULL REFERENCES ax.evidence(id),
    footnote_no  integer,
    PRIMARY KEY (draft_id, evidence_id)
);

-- 회의 결정·후속조치
CREATE TABLE ax.meeting_decision (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id        bigint NOT NULL REFERENCES ax.planning_meeting(id) ON DELETE CASCADE,
    recommendation_id bigint REFERENCES ax.recommendation(id),
    decision          text NOT NULL,
    follow_up_action  text,
    owner_dept_id     bigint REFERENCES ax.department(id),
    due_date          date,
    status            text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','DONE','DROPPED')),
    created_at        timestamptz NOT NULL DEFAULT now()
);

-- 연계 실행 결과: 실제 과제화·사업화·수출·기술이전 등
CREATE TABLE ax.linkage_execution (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id     bigint REFERENCES ax.recommendation(id),      -- AI 추천 기반이면 연결
    source_card_id        bigint NOT NULL REFERENCES ax.achievement_card(id),
    linkage_type_code     text NOT NULL REFERENCES ax.code_linkage_type(code),
    execution_type        text NOT NULL CHECK (execution_type IN
                           ('NEW_PROJECT','PROGRAM_APPLICATION','TECH_TRANSFER','COMMERCIALIZATION',
                            'EXPORT','LOCALIZATION','PILOT_TEST','OTHER')),
    resulting_project_id  bigint REFERENCES ax.project(id),             -- 신규 과제로 연결된 경우
    organization_id       bigint REFERENCES ax.organization(id),        -- 사업화 기업
    status                text NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED','IN_PROGRESS','COMPLETED','DROPPED')),
    executed_on           date,
    discovered_by_ax      boolean NOT NULL DEFAULT true,  -- AX 로 신규 발굴된 연계인지 (추가 연계후보 수 KPI)
    note                  text,
    created_by            bigint REFERENCES ax.app_user(id),
    created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX linkage_execution_card ON ax.linkage_execution(source_card_id);
CREATE INDEX linkage_execution_rec ON ax.linkage_execution(recommendation_id);
