SET search_path = ax, public;

-- 검증 케이스: 과거 실제 이어달리기 사례 또는 전문가 선정 셋
CREATE TABLE ax.eval_case (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text NOT NULL,
    case_type        text NOT NULL CHECK (case_type IN ('HISTORICAL_RELAY','EXPERT_PANEL')),
    query_type       text NOT NULL CHECK (query_type IN ('DEMAND','CARD')),  -- 입력: 수요 또는 선행성과
    demand_id        bigint REFERENCES ax.planning_demand(id),
    card_id          bigint REFERENCES ax.achievement_card(id),
    project_relation_id bigint REFERENCES ax.project_relation(id),          -- 실제 사례 근거
    tech_domain      text,
    note             text,
    created_by       bigint REFERENCES ax.app_user(id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    CHECK ((query_type = 'DEMAND' AND demand_id IS NOT NULL) OR (query_type = 'CARD' AND card_id IS NOT NULL))
);

-- 전문가 정답 후보
CREATE TABLE ax.eval_ground_truth (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id           bigint NOT NULL REFERENCES ax.eval_case(id) ON DELETE CASCADE,
    expected_card_id  bigint REFERENCES ax.achievement_card(id),     -- 수요 입력 시 정답 성과
    expected_demand_id bigint REFERENCES ax.planning_demand(id),     -- 성과 입력 시 정답 수요
    expected_program_id bigint REFERENCES ax.program(id),
    expected_project_id bigint REFERENCES ax.project(id),            -- 실제 후속과제
    linkage_type_code text REFERENCES ax.code_linkage_type(code),
    importance        text NOT NULL DEFAULT 'MAJOR' CHECK (importance IN ('MAJOR','MINOR')), -- 주요 후보 여부
    expert_id         bigint REFERENCES ax.app_user(id),
    opinion           text,
    CHECK (num_nonnulls(expected_card_id, expected_demand_id, expected_program_id, expected_project_id) >= 1)
);
CREATE INDEX eval_ground_truth_case ON ax.eval_ground_truth(case_id);

-- 평가 실행 (케이스별 match_run 과 연결)
CREATE TABLE ax.eval_run (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL,
    top_k        integer NOT NULL DEFAULT 10 CHECK (top_k > 0),
    config       jsonb NOT NULL DEFAULT '{}'::jsonb,   -- 모델·규칙 버전 등
    metrics      jsonb NOT NULL DEFAULT '{}'::jsonb,   -- 집계 결과 캐시 {"top_k_recall_major":0.83,...}
    created_by   bigint REFERENCES ax.app_user(id),
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ax.eval_run_case (
    eval_run_id  bigint NOT NULL REFERENCES ax.eval_run(id) ON DELETE CASCADE,
    case_id      bigint NOT NULL REFERENCES ax.eval_case(id) ON DELETE CASCADE,
    match_run_id bigint NOT NULL REFERENCES ax.match_run(id),
    PRIMARY KEY (eval_run_id, case_id)
);

-- 업무시간 측정 (기존 수작업 vs AX)
CREATE TABLE ax.work_time_measurement (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type     text NOT NULL CHECK (task_type IN
                   ('RESEARCH',          -- 관련 성과·과제 조사
                    'DOCUMENT_READING',  -- 자료 열람
                    'CANDIDATE_LIST',    -- 후보목록 작성
                    'REVIEW_MATERIAL')), -- 통합기획 검토자료 작성
    method        text NOT NULL CHECK (method IN ('MANUAL','AX')),
    case_id       bigint REFERENCES ax.eval_case(id),
    demand_id     bigint REFERENCES ax.planning_demand(id),
    user_id       bigint REFERENCES ax.app_user(id),
    minutes       numeric(8,1) NOT NULL CHECK (minutes >= 0),
    candidates_found integer,                -- 추가 연계후보 수 비교용
    measured_on   date NOT NULL DEFAULT current_date,
    note          text
);

-- 만족도 설문
CREATE TABLE ax.satisfaction_survey (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint REFERENCES ax.app_user(id),
    respondent_role text CHECK (respondent_role IN ('PLANNER','DEPT_REVIEWER','EXPERT','OTHER')),
    score        smallint NOT NULL CHECK (score BETWEEN 1 AND 5),
    aspects      jsonb NOT NULL DEFAULT '{}'::jsonb,  -- {"usefulness":5,"evidence":4,...}
    comment      text,
    submitted_at timestamptz NOT NULL DEFAULT now()
);
