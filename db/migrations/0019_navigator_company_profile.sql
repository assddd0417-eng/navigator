CREATE TABLE ax.company_patent (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    application_no   text NOT NULL,                 -- 출원번호 (예: 10-2023-0012345)
    registration_no  text,                          -- 등록번호
    title            text NOT NULL,
    abstract         text,
    ipc_codes        text[] NOT NULL DEFAULT '{}',  -- 기술분류(IPC)
    status           text NOT NULL DEFAULT 'APPLIED' CHECK (status IN ('APPLIED','REGISTERED','LAPSED')),
    applied_on       date,
    registered_on    date,
    origin           text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    verified_at      timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, application_no),
    CHECK (status <> 'REGISTERED' OR registration_no IS NOT NULL)
);
CREATE INDEX company_patent_title_trgm ON ax.company_patent USING gin (title gin_trgm_ops);
CREATE INDEX company_patent_ipc ON ax.company_patent USING gin (ipc_codes);
CREATE TRIGGER trg_company_patent_updated BEFORE UPDATE ON ax.company_patent
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- -----------------------------------------------------------------------------
-- 인증·지정
-- -----------------------------------------------------------------------------
CREATE TABLE ax.company_certification (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    cert_type_code      text NOT NULL REFERENCES ax.code_certification_type(code),
    cert_no             text,
    issuer              text,
    issued_on           date,
    expires_on          date,
    evidence_document_id bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,  -- 증빙 PDF (기존 문서 기능 재사용)
    origin              text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    verified_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (expires_on IS NULL OR issued_on IS NULL OR expires_on >= issued_on)
);
CREATE INDEX company_certification_org ON ax.company_certification(organization_id);
CREATE INDEX company_certification_type ON ax.company_certification(cert_type_code);
CREATE TRIGGER trg_company_certification_updated BEFORE UPDATE ON ax.company_certification
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- -----------------------------------------------------------------------------
-- 신용등급 (기업 자신과 권한 있는 기관 담당자만 열람. LLM 연계이유에는 보내지 않음)
-- -----------------------------------------------------------------------------
CREATE TABLE ax.company_credit_rating (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    agency              text NOT NULL CHECK (agency IN ('NICE','KED','SELF','OTHER')),  -- 평가기관 (SELF = 자가입력, 평가서 미첨부)
    grade               text NOT NULL,                  -- 예: BBB+, B0, CCC
    rated_on            date,
    valid_until         date,
    evidence_document_id bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,  -- 평가서 PDF
    origin              text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    verified_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (valid_until IS NULL OR rated_on IS NULL OR valid_until >= rated_on)
);
CREATE INDEX company_credit_rating_org ON ax.company_credit_rating(organization_id, rated_on DESC);
CREATE TRIGGER trg_company_credit_rating_updated BEFORE UPDATE ON ax.company_credit_rating
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();
COMMENT ON TABLE ax.company_credit_rating IS
  '신용등급. 사업자번호만으로는 보이지 않음 (관리 링크 또는 권한 있는 기관 담당자). LLM 외부 전송 금지';

-- -----------------------------------------------------------------------------
-- R&D 수행 이력 (내부 과제와 같으면 internal_project_id 로 연결)
-- -----------------------------------------------------------------------------
CREATE TABLE ax.company_rnd_history (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    project_no          text,                           -- 과제번호 (NTIS·부처 과제번호)
    title               text NOT NULL,
    funding_agency      text,                           -- 전담·발주 기관
    start_date          date,
    end_date            date,
    amount_krw          bigint CHECK (amount_krw >= 0),
    role                text NOT NULL DEFAULT 'LEAD' CHECK (role IN ('LEAD','PARTICIPANT')),  -- 주관/참여
    summary             text,
    internal_project_id bigint REFERENCES ax.project(id) ON DELETE SET NULL,
    origin              text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    verified_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX company_rnd_history_org ON ax.company_rnd_history(organization_id);
CREATE UNIQUE INDEX company_rnd_history_org_projno ON ax.company_rnd_history(organization_id, project_no)
    WHERE project_no IS NOT NULL;
CREATE INDEX company_rnd_history_title_trgm ON ax.company_rnd_history USING gin (title gin_trgm_ops);
CREATE TRIGGER trg_company_rnd_history_updated BEFORE UPDATE ON ax.company_rnd_history
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- -----------------------------------------------------------------------------
-- 관리 링크 (로그인 대신 쓰는 비밀 주소). 비밀값 원문은 저장하지 않고 SHA-256 해시만 둔다.
-- -----------------------------------------------------------------------------
CREATE TABLE ax.company_access_link (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id    bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    email              text NOT NULL,
    token_hash         text NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),  -- sha256 hex
    purpose            text NOT NULL DEFAULT 'MANAGE' CHECK (purpose IN ('MANAGE')),
    expires_at         timestamptz NOT NULL,
    email_verified_at  timestamptz,                     -- 링크를 처음 연 시각 = 이메일 소유 확인
    last_used_at       timestamptz,
    revoked_at         timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CHECK (expires_at > created_at)
);
CREATE INDEX company_access_link_org ON ax.company_access_link(organization_id, created_at DESC);

