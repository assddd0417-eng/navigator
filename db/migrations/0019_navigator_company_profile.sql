-- 0019: Navigator 1단계 — 기업 프로필 확장 (기업이 어떤 곳인지)
--   기업 담당자는 로그인 없이 사업자번호로 프로필을 만들고, 등록 이메일로 받은
--   관리 링크(company_access_link)로만 고친다. 기관 담당자는 기존 로그인·역할 그대로.
--
--   기존 테이블은 지우거나 바꾸지 않고 칸만 더한다.
--   사업자번호는 기존 organization.business_reg_no (UNIQUE) 를 그대로 쓴다.
--     → Navigator 는 하이픈 없는 숫자 10자리로 정규화해서 저장·조회한다.
--
--   값의 출처(origin): SELF 기업 자가입력 / EXTERNAL 외부 수집 / INTERNAL 내부 과제·성과카드 / STAFF 기관 담당자
--   확인 여부(verified_at): 외부 출처나 담당자가 확인하면 시각을 넣는다. NULL = 미확인.
--   칸별 상세 출처·자가입력과 외부값의 차이는 0020 company_field_source 에 둔다.
-- =============================================================================
