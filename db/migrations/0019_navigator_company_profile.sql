ALTER TABLE ax.company_profile
    ADD COLUMN representative_name  text,                 -- 대표자명 (국세청 진위확인 입력값)
    ADD COLUMN opened_on            date,                 -- 개업일 (국세청 진위확인 입력값)
    ADD COLUMN established_on       date,                 -- 설립일 (법인 설립일, 개업일과 다를 수 있음)
    ADD COLUMN employee_count       integer CHECK (employee_count >= 0),
    ADD COLUMN annual_revenue_krw   bigint  CHECK (annual_revenue_krw >= 0),  -- 최근 연매출 (원)
    ADD COLUMN revenue_year         smallint CHECK (revenue_year BETWEEN 1900 AND 2100),
    ADD COLUMN region               text CHECK (region IN (
                                      '서울','부산','대구','인천','광주','대전','울산','세종','경기',
                                      '강원','충북','충남','전북','전남','경북','경남','제주')),
    ADD COLUMN address              text,
    -- 휴·폐업 상태 (국세청 상태조회: 01 계속, 02 휴업, 03 폐업)
    ADD COLUMN business_status      text NOT NULL DEFAULT 'UNKNOWN'
                                    CHECK (business_status IN ('ACTIVE','SUSPENDED','CLOSED','UNKNOWN')),
    ADD COLUMN business_status_checked_at timestamptz,
    -- 사업자 진위확인 결과: VERIFIED 확인됨 / UNVERIFIED 미확인(확인 불가·미실시) / FAILED 불일치
    ADD COLUMN biz_verify_status    text NOT NULL DEFAULT 'UNVERIFIED'
                                    CHECK (biz_verify_status IN ('VERIFIED','UNVERIFIED','FAILED')),
    ADD COLUMN biz_verified_at      timestamptz,
    ADD COLUMN registered_email     text,                 -- 처음 등록할 때 받은 이메일 (관리 링크는 이 주소로만)
    ADD COLUMN registration_channel text CHECK (registration_channel IN ('SELF','STAFF','EXTERNAL','INTERNAL')),
    ADD COLUMN created_at           timestamptz DEFAULT now();

COMMENT ON COLUMN ax.company_profile.biz_verify_status IS
  '국세청 사업자 진위확인 결과. 화면의 확인됨/미확인 표시 기준';
COMMENT ON COLUMN ax.company_profile.registered_email IS
  '관리 링크 수신 이메일. 신용정보와 함께 관리 링크가 있어야 보임';

