-- =============================================================================
-- 0020: Navigator 1단계 — 출처 기록 (그 값이 어디서 왔는지)
--   external_source      연결할 외부 출처 목록 (출처마다 연결 부품 1개, 목업/실제 전환)
--   external_fetch_job   수집 실행 기록 (성공/실패, 오류)
--   external_raw_record  외부에서 받은 원본 그대로 (내용 해시로 바뀜 감지)
--   company_field_source 칸별 출처와 확인 여부. 자가입력과 외부값이 다르면 둘 다 보관
--
-- 출처의 실제 모드(MOCK/LIVE)는 백엔드 설정(SOURCE_<CODE>=mock|live)이 정한다.
-- 이 표의 mode 는 기본값·화면 표시용이며, 실행 때 쓴 모드는 external_fetch_job.mode 에 남는다.
-- =============================================================================
SET search_path = ax, public;

CREATE TABLE ax.external_source (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            text NOT NULL UNIQUE,              -- 설정 이름의 기준 (SOURCE_<code>)
    name            text NOT NULL,
    provider        text,                              -- 제공 기관
    method          text NOT NULL CHECK (method IN ('API','CRAWL','FILE')),
    mode            text NOT NULL DEFAULT 'MOCK' CHECK (mode IN ('MOCK','LIVE')),
    data_kind       text NOT NULL CHECK (data_kind IN
                     ('BIZ_STATUS','PATENT','CREDIT','FINANCE','RND','CERTIFICATION','ANNOUNCEMENT')),
    fetch_interval  interval,                          -- 수집 주기 (NULL = 요청 시에만)
    requires_key    boolean NOT NULL DEFAULT true,
    is_paid         boolean NOT NULL DEFAULT false,
    is_active       boolean NOT NULL DEFAULT true,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_external_source_updated BEFORE UPDATE ON ax.external_source
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

