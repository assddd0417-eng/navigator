CREATE TABLE ax.external_fetch_job (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id        bigint NOT NULL REFERENCES ax.external_source(id),
    organization_id  bigint REFERENCES ax.organization(id) ON DELETE SET NULL,  -- 대상 기업 (전체 수집이면 NULL)
    mode             text NOT NULL CHECK (mode IN ('MOCK','LIVE')),
    trigger_kind     text NOT NULL DEFAULT 'ON_DEMAND' CHECK (trigger_kind IN ('ON_DEMAND','SCHEDULED','REGISTRATION')),
    request_params   jsonb NOT NULL DEFAULT '{}'::jsonb,  -- 비밀값(API 키)은 넣지 않는다
    status           text NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    records_count    integer NOT NULL DEFAULT 0,
    error_message    text,
    started_at       timestamptz NOT NULL DEFAULT now(),
    finished_at      timestamptz,
    CHECK (finished_at IS NULL OR finished_at >= started_at),
    CHECK (status = 'RUNNING' OR finished_at IS NOT NULL)
);
CREATE INDEX external_fetch_job_source ON ax.external_fetch_job(source_id, started_at DESC);
CREATE INDEX external_fetch_job_org ON ax.external_fetch_job(organization_id, started_at DESC);

CREATE TABLE ax.external_raw_record (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fetch_job_id     bigint NOT NULL REFERENCES ax.external_fetch_job(id) ON DELETE CASCADE,
    source_id        bigint NOT NULL REFERENCES ax.external_source(id),
    organization_id  bigint REFERENCES ax.organization(id) ON DELETE SET NULL,
    external_key     text NOT NULL,                     -- 출처 안에서의 식별자 (사업자번호, 출원번호 등)
    payload          jsonb NOT NULL,                    -- 받은 원본 그대로
    content_hash     text NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),  -- sha256(정규화 JSON)
    fetched_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX external_raw_record_key ON ax.external_raw_record(source_id, external_key, fetched_at DESC);
CREATE INDEX external_raw_record_job ON ax.external_raw_record(fetch_job_id);

CREATE TABLE ax.company_field_source (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    field_name          text NOT NULL,                  -- 예: business_status, employee_count, annual_revenue_krw
    value               jsonb,
    source_kind         text NOT NULL CHECK (source_kind IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    external_source_id  bigint REFERENCES ax.external_source(id),
    raw_record_id       bigint REFERENCES ax.external_raw_record(id) ON DELETE SET NULL,
    is_verified         boolean NOT NULL DEFAULT false,
    verified_at         timestamptz,
    verified_by         bigint REFERENCES ax.app_user(id),  -- 담당자 확인이면 사용자, 외부 확인이면 NULL
    recorded_at         timestamptz NOT NULL DEFAULT now(),
    CHECK (source_kind <> 'EXTERNAL' OR external_source_id IS NOT NULL),
    CHECK (is_verified = (verified_at IS NOT NULL))
);
-- 같은 기업·칸·출처의 현재값은 1행 (이전 값은 audit_log 에 남는다)
CREATE UNIQUE INDEX company_field_source_current
    ON ax.company_field_source (organization_id, field_name, source_kind, COALESCE(external_source_id, 0));
CREATE TRIGGER trg_company_field_source_audit AFTER INSERT OR UPDATE OR DELETE ON ax.company_field_source
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();

-- 칸별 값 비교: 외부 확인값을 앞에, 자가입력과 다르면 differs = true
CREATE VIEW ax.v_company_field_compare AS
SELECT organization_id, field_name,
       (array_agg(value ORDER BY is_verified DESC, (source_kind = 'EXTERNAL') DESC, recorded_at DESC))[1] AS preferred_value,
       bool_or(is_verified) AS any_verified,
       count(DISTINCT value) > 1 AS differs,
       jsonb_agg(jsonb_build_object('source_kind', source_kind, 'external_source_id', external_source_id,
                                    'value', value, 'is_verified', is_verified, 'recorded_at', recorded_at)
                 ORDER BY is_verified DESC, (source_kind = 'EXTERNAL') DESC, recorded_at DESC) AS sources
  FROM ax.company_field_source
 GROUP BY organization_id, field_name;
