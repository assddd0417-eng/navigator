CREATE TABLE ax.announcement (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_no     text NOT NULL UNIQUE,              -- 공고번호
    title               text NOT NULL,
    agency_name         text NOT NULL,                     -- 공고 기관 (표시용)
    agency_org_id       bigint REFERENCES ax.organization(id),
    domain              text NOT NULL DEFAULT 'DEFENSE_RND'
                        CHECK (domain IN ('DEFENSE_RND','GENERAL_SUPPORT','PROCUREMENT')),
    program_id          bigint REFERENCES ax.program(id) ON DELETE SET NULL,  -- 사업트랙 (기존 program)
    summary             text,                              -- 사업 목적·개요
    target_desc         text,                              -- 지원대상 (원문 그대로)
    support_amount_krw  bigint CHECK (support_amount_krw >= 0),   -- 과제당 최대 지원금
    support_period_months smallint CHECK (support_period_months > 0),
    receipt_start       date,
    receipt_end         date,                              -- 접수 마감
    source_kind         text NOT NULL DEFAULT 'MANUAL' CHECK (source_kind IN ('MANUAL','PDF','EXTERNAL')),
    external_source_id  bigint REFERENCES ax.external_source(id),
    source_url          text,
    document_id         bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,  -- 공고문 원문
    status              text NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('DRAFT','PUBLISHED','CANCELLED')),
    created_by          bigint REFERENCES ax.app_user(id),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (receipt_end IS NULL OR receipt_start IS NULL OR receipt_end >= receipt_start),
    CHECK (source_kind <> 'EXTERNAL' OR external_source_id IS NOT NULL)
);
CREATE INDEX announcement_receipt ON ax.announcement(receipt_end) WHERE status = 'PUBLISHED';
CREATE INDEX announcement_program ON ax.announcement(program_id);
CREATE INDEX announcement_title_trgm ON ax.announcement USING gin (title gin_trgm_ops);
CREATE TRIGGER trg_announcement_updated BEFORE UPDATE ON ax.announcement
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- -----------------------------------------------------------------------------
-- 자격요건 한 줄씩
-- -----------------------------------------------------------------------------
CREATE TABLE ax.announcement_requirement (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id   bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    req_type_code     text NOT NULL REFERENCES ax.code_requirement_type(code),
    rule              jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_mandatory      boolean NOT NULL DEFAULT true,       -- true 필수 / false 우대
    description       text NOT NULL,                       -- 사람이 읽는 문장 (보완질문·화면에 그대로)
    evidence_id       bigint REFERENCES ax.evidence(id) ON DELETE SET NULL,  -- 공고문 청크 근거 (문서·쪽)
    source_quote      text,                                -- 원문 인용 (근거 청크가 없을 때도 남김)
    source_page       integer CHECK (source_page > 0),
    origin            text NOT NULL DEFAULT 'MANUAL' CHECK (origin IN ('MANUAL','AI_EXTRACTED')),
    sort_order        smallint NOT NULL DEFAULT 0,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (jsonb_typeof(rule) = 'object')
);
CREATE INDEX announcement_requirement_ann ON ax.announcement_requirement(announcement_id, sort_order);
CREATE TRIGGER trg_announcement_requirement_updated BEFORE UPDATE ON ax.announcement_requirement
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

