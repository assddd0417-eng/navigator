-- =============================================================================
-- 0022: Navigator 3단계 — 벡터와 매칭 결과
--   company_embedding               기업을 관점별로 나눈 벡터 (요약/보유기술/특허/R&D이력/주요사업)
--   announcement_embedding          공고를 관점별로 나눈 벡터 (요약/요구기술/사업목적)
--   company_match_run               매칭 한 번 (방향, 규칙 스냅샷, 모델, 실행자)
--   company_recommendation          기업↔공고 한 쌍 (총점, 판정, 연계이유)
--   company_recommendation_score    기준별 점수
--   eligibility_check               자격요건별 판정 (충족/미충족/모름 + 보완질문)
--   company_recommendation_evidence 근거 (특허·R&D 이력·공고 조항)
--   eligibility_answer              보완질문에 대한 기업 답 (다시 판정할 때 읽음)
--
-- 판정: 필수 요건 중 하나라도 미충족 → 부적격 / 미충족은 없고 모름이 있으면 → 정보부족 / 모두 충족 → 적합.
-- 신용등급 값은 판정 상세(detail)에 남기지 않는다 (충족 여부만). LLM 연계이유에도 보내지 않는다.
-- =============================================================================
SET search_path = ax, public;

-- -----------------------------------------------------------------------------
-- 벡터 (기존 card_embedding·demand_embedding 과 같은 모양: 모델별, 원문 해시로 재임베딩 판단)
-- -----------------------------------------------------------------------------
CREATE TABLE ax.company_embedding (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    facet            text NOT NULL CHECK (facet IN ('SUMMARY','TECH','PATENT','RND','BUSINESS')),
    source_table     text,                  -- 행 단위 벡터: company_patent, company_rnd_history, company_technology, project
    source_id        bigint,
    model_id         smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_text      text NOT NULL,
    source_sha256    char(64) NOT NULL,
    embedding        vector(1024) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (organization_id, facet, source_table, source_id, model_id)
);
CREATE INDEX company_embedding_org ON ax.company_embedding(organization_id);
CREATE INDEX company_embedding_hnsw_tech ON ax.company_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet IN ('TECH','PATENT','RND');
CREATE INDEX company_embedding_hnsw_summary ON ax.company_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet IN ('SUMMARY','BUSINESS');

CREATE TABLE ax.announcement_embedding (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id  bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    facet            text NOT NULL CHECK (facet IN ('SUMMARY','TECH_NEED','PURPOSE')),
    source_table     text,                  -- 요구기술별: announcement_tech_need
    source_id        bigint,
    model_id         smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_text      text NOT NULL,
    source_sha256    char(64) NOT NULL,
    embedding        vector(1024) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (announcement_id, facet, source_table, source_id, model_id)
);
CREATE INDEX announcement_embedding_ann ON ax.announcement_embedding(announcement_id);
CREATE INDEX announcement_embedding_hnsw_tech ON ax.announcement_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'TECH_NEED';
CREATE INDEX announcement_embedding_hnsw_summary ON ax.announcement_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet IN ('SUMMARY','PURPOSE');

-- -----------------------------------------------------------------------------
-- 매칭 실행과 결과
-- -----------------------------------------------------------------------------
CREATE TABLE ax.company_match_run (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction        text NOT NULL CHECK (direction IN ('ANNOUNCEMENT_TO_COMPANY','COMPANY_TO_ANNOUNCEMENT')),
    announcement_id  bigint REFERENCES ax.announcement(id) ON DELETE CASCADE,
    organization_id  bigint REFERENCES ax.organization(id) ON DELETE CASCADE,
    model_id         smallint NOT NULL REFERENCES ax.embedding_model(id),
    rule_snapshot    jsonb NOT NULL,         -- 가중치·후보 수·판정 규칙 버전
    params           jsonb NOT NULL DEFAULT '{}'::jsonb,
    requested_by     bigint REFERENCES ax.app_user(id),   -- 기관 담당자
    requested_via    text NOT NULL CHECK (requested_via IN ('STAFF','COMPANY_LINK','PUBLIC','SYSTEM')),
    candidate_count  integer NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CHECK (direction <> 'ANNOUNCEMENT_TO_COMPANY' OR announcement_id IS NOT NULL),
    CHECK (direction <> 'COMPANY_TO_ANNOUNCEMENT' OR organization_id IS NOT NULL)
);
CREATE INDEX company_match_run_ann ON ax.company_match_run(announcement_id, created_at DESC);
CREATE INDEX company_match_run_org ON ax.company_match_run(organization_id, created_at DESC);

CREATE TABLE ax.company_recommendation (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_run_id     bigint NOT NULL REFERENCES ax.company_match_run(id) ON DELETE CASCADE,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    announcement_id  bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    rank             integer NOT NULL CHECK (rank >= 1),
    total_score      numeric(6,5) NOT NULL CHECK (total_score BETWEEN 0 AND 1),
    verdict          text NOT NULL CHECK (verdict IN ('ELIGIBLE','NEEDS_INFO','INELIGIBLE')),
    mandatory_met    smallint NOT NULL DEFAULT 0,
    mandatory_total  smallint NOT NULL DEFAULT 0,
    preferred_met    smallint NOT NULL DEFAULT 0,
    preferred_total  smallint NOT NULL DEFAULT 0,
    rationale        text NOT NULL,           -- 연계이유 (템플릿, 신용등급 값 없음)
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (match_run_id, organization_id, announcement_id)
);
CREATE INDEX company_recommendation_org ON ax.company_recommendation(organization_id, created_at DESC);
CREATE INDEX company_recommendation_ann ON ax.company_recommendation(announcement_id, created_at DESC);

CREATE TABLE ax.company_recommendation_score (
    recommendation_id bigint NOT NULL REFERENCES ax.company_recommendation(id) ON DELETE CASCADE,
    criterion        text NOT NULL CHECK (criterion IN ('TECH','IPC','PURPOSE','PREFERENCE')),
    score            numeric(6,5) NOT NULL CHECK (score BETWEEN 0 AND 1),
    weight           numeric(6,5) NOT NULL CHECK (weight BETWEEN 0 AND 1),
    method           text NOT NULL,
    detail           jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (recommendation_id, criterion)
);

CREATE TABLE ax.eligibility_check (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint NOT NULL REFERENCES ax.company_recommendation(id) ON DELETE CASCADE,
    requirement_id    bigint NOT NULL REFERENCES ax.announcement_requirement(id) ON DELETE CASCADE,
    result            text NOT NULL CHECK (result IN ('MET','UNMET','UNKNOWN')),
    is_mandatory      boolean NOT NULL,
    reason            text NOT NULL,          -- 판정 이유 (사람이 읽는 문장)
    question          text,                   -- 모름(UNKNOWN)일 때 보완질문
    detail            jsonb NOT NULL DEFAULT '{}'::jsonb,  -- 비교한 값 (신용등급 값은 넣지 않음)
    self_declared     boolean NOT NULL DEFAULT false,      -- 기업 답(eligibility_answer)으로 판정
    UNIQUE (recommendation_id, requirement_id),
    CHECK (result = 'UNKNOWN' OR question IS NULL)
);

CREATE TABLE ax.company_recommendation_evidence (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id bigint NOT NULL REFERENCES ax.company_recommendation(id) ON DELETE CASCADE,
    kind              text NOT NULL CHECK (kind IN ('TECH_MATCH','IPC_MATCH','REQUIREMENT')),
    company_source_table text,               -- company_patent / company_rnd_history / project ...
    company_source_id bigint,
    company_text      text,                  -- 근거 문장 (특허 제목 등)
    tech_need_id      bigint REFERENCES ax.announcement_tech_need(id) ON DELETE CASCADE,
    requirement_id    bigint REFERENCES ax.announcement_requirement(id) ON DELETE CASCADE,
    evidence_id       bigint REFERENCES ax.evidence(id) ON DELETE SET NULL,   -- 공고문 원문 근거
    quote             text,                  -- 공고 조항 원문 인용
    page              integer,
    similarity        numeric(6,5),
    sort_order        smallint NOT NULL DEFAULT 0
);
CREATE INDEX company_recommendation_evidence_rec ON ax.company_recommendation_evidence(recommendation_id, sort_order);

-- 보완질문에 대한 기업(또는 담당자)의 답. 같은 기업·요건은 최신 답 1개
CREATE TABLE ax.eligibility_answer (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    requirement_id    bigint NOT NULL REFERENCES ax.announcement_requirement(id) ON DELETE CASCADE,
    answer            jsonb NOT NULL,         -- {"value": 7} (TRL) / {"value": true} (충족 여부)
    answered_via      text NOT NULL CHECK (answered_via IN ('COMPANY_LINK','STAFF')),
    answered_by       bigint REFERENCES ax.app_user(id),
    answered_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, requirement_id)
);
CREATE TRIGGER trg_eligibility_answer_audit AFTER INSERT OR UPDATE OR DELETE ON ax.eligibility_answer
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();
