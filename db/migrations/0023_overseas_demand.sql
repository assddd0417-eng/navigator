-- 해외 수요 출처
CREATE TABLE ax.overseas_source (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_no        text NOT NULL UNIQUE,                   -- 예: 'S1' (정리 엑셀의 출처 번호)
    issuer           text NOT NULL,                          -- 발행 기관 (예: EU 집행위원회, 폴란드 국방부)
    title            text NOT NULL,
    published_on     text,                                   -- 발행일 (월까지만 알 때가 있어 문자열)
    url              text NOT NULL CHECK (url ~ '^https?://'),
    source_kind      text NOT NULL CHECK (source_kind IN
                      ('ROADMAP',      -- 해외 기술 로드맵·전략
                       'CALL',         -- 해외 공모
                       'EXPORT_REQ',   -- 수출 대상국 요구
                       'DOMESTIC')),   -- 국내 근거 (비교용)
    license_note     text NOT NULL CHECK (btrim(license_note) <> ''),  -- 이용 조건 (예: CC BY 4.0, 표시 없음)
    allow_full_text  boolean NOT NULL DEFAULT false,         -- 원문 저장 허용 여부
    checked_on       date NOT NULL,                          -- 출처·이용 조건을 확인한 날
    country_code     char(2),                                -- ISO 3166-1 alpha-2 (EU 등은 NULL)
    security_code    text NOT NULL DEFAULT 'PUBLIC' REFERENCES ax.code_security_level(code),
    document_id      bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,  -- 원문 (허용된 경우만)
    note             text,
    created_by       bigint REFERENCES ax.app_user(id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CHECK (document_id IS NULL OR allow_full_text)
);
CREATE TRIGGER trg_overseas_source_updated BEFORE UPDATE ON ax.overseas_source
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 해외 수요
CREATE TABLE ax.overseas_demand (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_no         text NOT NULL UNIQUE,                  -- 예: 'D01'
    title             text NOT NULL,
    demand_kind       text NOT NULL CHECK (demand_kind IN ('ROADMAP','CALL','EXPORT_REQ')),
    region            text NOT NULL,                         -- 국가/기관 (예: 폴란드, EU)
    tech_area         text,                                  -- 기술분류 (자유 기재)
    tech_taxonomy_id  bigint REFERENCES ax.tech_taxonomy(id),
    target_system     text,                                  -- 무기체계/품목 (자유 기재)
    weapon_system_id  bigint REFERENCES ax.weapon_system(id),
    requirement       text NOT NULL,                         -- 요구 성능·요구 사항 서술
    target_period     text,                                  -- 목표 시기 (예: '2028~2030')
    quote             text,                                  -- 원문 인용 (짧게)
    confidence        text NOT NULL DEFAULT 'MEDIUM' CHECK (confidence IN ('HIGH','MEDIUM','LOW')),
    note              text,
    status            text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','CONFIRMED','ARCHIVED')),
    security_code     text NOT NULL DEFAULT 'PUBLIC' REFERENCES ax.code_security_level(code),
    created_by        bigint REFERENCES ax.app_user(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX overseas_demand_title_trgm ON ax.overseas_demand USING gin (title gin_trgm_ops);
CREATE TRIGGER trg_overseas_demand_updated BEFORE UPDATE ON ax.overseas_demand
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

-- 해외 수요 ↔ 출처 (한 수요가 여러 출처에서 나올 수 있다)
CREATE TABLE ax.overseas_demand_source (
    overseas_demand_id bigint NOT NULL REFERENCES ax.overseas_demand(id) ON DELETE CASCADE,
    source_id          bigint NOT NULL REFERENCES ax.overseas_source(id),
    is_primary         boolean NOT NULL DEFAULT false,
    PRIMARY KEY (overseas_demand_id, source_id)
);

-- 요구 성능 (정량이면 값·단위, 아니면 서술)
CREATE TABLE ax.overseas_demand_performance (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    overseas_demand_id bigint NOT NULL REFERENCES ax.overseas_demand(id) ON DELETE CASCADE,
    metric_name        text NOT NULL,
    comparator         text NOT NULL DEFAULT 'GTE' CHECK (comparator IN ('GTE','LTE','EQ','RANGE')),
    required_value     numeric,
    required_max       numeric,
    required_text      text,
    unit               text,
    quote              text,
    sort_order         smallint NOT NULL DEFAULT 0,
    CHECK (required_value IS NOT NULL OR required_text IS NOT NULL)
);
CREATE INDEX overseas_demand_performance_demand ON ax.overseas_demand_performance(overseas_demand_id);

-- 패싯 임베딩 (demand_embedding 과 같은 모양)
CREATE TABLE ax.overseas_demand_embedding (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    overseas_demand_id bigint NOT NULL REFERENCES ax.overseas_demand(id) ON DELETE CASCADE,
    facet              text NOT NULL CHECK (facet IN ('SUMMARY','TECH_NEED','PERFORMANCE','APPLICATION_ENV')),
    source_table       text,
    source_id          bigint,
    model_id           smallint NOT NULL REFERENCES ax.embedding_model(id),
    source_text        text NOT NULL,
    source_sha256      char(64) NOT NULL,
    embedding          vector(1024) NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (overseas_demand_id, facet, source_table, source_id, model_id)
);
CREATE INDEX overseas_demand_embedding_demand ON ax.overseas_demand_embedding(overseas_demand_id);
CREATE INDEX overseas_demand_embedding_hnsw_summary ON ax.overseas_demand_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE facet = 'SUMMARY';

