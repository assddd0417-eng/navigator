-- 보안등급: 해외 수요는 연결된 출처 중 가장 높은 등급 이상이어야 한다
CREATE OR REPLACE FUNCTION ax.check_overseas_demand_security() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_demand_id bigint;
    v_demand_rank smallint;
    v_source_rank smallint;
BEGIN
    IF TG_TABLE_NAME = 'overseas_demand' THEN
        v_demand_id := NEW.id;
    ELSE
        v_demand_id := NEW.overseas_demand_id;
    END IF;
    SELECT l.level_rank INTO v_demand_rank
      FROM ax.overseas_demand d JOIN ax.code_security_level l ON l.code = d.security_code
     WHERE d.id = v_demand_id;
    SELECT max(l.level_rank) INTO v_source_rank
      FROM ax.overseas_demand_source ds
      JOIN ax.overseas_source s ON s.id = ds.source_id
      JOIN ax.code_security_level l ON l.code = s.security_code
     WHERE ds.overseas_demand_id = v_demand_id;
    IF v_source_rank IS NOT NULL AND v_demand_rank < v_source_rank THEN
        RAISE EXCEPTION '해외 수요(%)의 보안등급이 출처 보안등급보다 낮습니다', v_demand_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_overseas_demand_security
    AFTER INSERT OR UPDATE OF security_code ON ax.overseas_demand
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ax.check_overseas_demand_security();
CREATE CONSTRAINT TRIGGER trg_overseas_demand_source_security
    AFTER INSERT OR UPDATE ON ax.overseas_demand_source
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ax.check_overseas_demand_security();

