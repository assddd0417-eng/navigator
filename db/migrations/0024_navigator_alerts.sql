-- 0024: Navigator 공고 알림 구독
--   alert_subscription  기업별 수신자 설정. 이메일 확인 후에만 발송
--   alert_notification  공고별로 보낸 알림 (화면 + 메일)
SET search_path = ax, public;

CREATE TABLE ax.alert_subscription (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    email               text NOT NULL CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    keywords            text[] NOT NULL DEFAULT '{}',     -- 관심 분야. 비어 있으면 전체
    min_score           numeric(4,3) NOT NULL DEFAULT 0 CHECK (min_score BETWEEN 0 AND 1),
    include_needs_info  boolean NOT NULL DEFAULT true,    -- 정보부족 공고도 받기
    channels            text[] NOT NULL DEFAULT '{SCREEN,EMAIL}'
                        CHECK (cardinality(channels) > 0 AND channels <@ ARRAY['SCREEN','EMAIL']),
    is_active           boolean NOT NULL DEFAULT true,
    confirm_token_hash  text UNIQUE,
    confirm_expires_at  timestamptz,
    email_confirmed_at  timestamptz,
    unsubscribed_at     timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, email)
);
CREATE INDEX alert_subscription_live ON ax.alert_subscription(organization_id)
    WHERE is_active AND email_confirmed_at IS NOT NULL AND unsubscribed_at IS NULL;

CREATE TABLE ax.alert_notification (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id     bigint NOT NULL REFERENCES ax.alert_subscription(id) ON DELETE CASCADE,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    announcement_id     bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    recommendation_id   bigint REFERENCES ax.company_recommendation(id) ON DELETE SET NULL,
    verdict             text NOT NULL CHECK (verdict IN ('ELIGIBLE','NEEDS_INFO')),
    total_score         numeric(6,5) NOT NULL,
    rationale           text NOT NULL,
    status              text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','FAILED','READ')),
    error               text,
    unsubscribe_token_hash text UNIQUE,                 -- 메일마다 새 토큰
    created_at          timestamptz NOT NULL DEFAULT now(),
    sent_at             timestamptz,
    read_at             timestamptz,
    UNIQUE (subscription_id, announcement_id)
);
CREATE INDEX alert_notification_org ON ax.alert_notification(organization_id, created_at DESC);
CREATE INDEX alert_notification_ann ON ax.alert_notification(announcement_id);

CREATE TRIGGER trg_alert_subscription_audit AFTER INSERT OR UPDATE OR DELETE ON ax.alert_subscription
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();
