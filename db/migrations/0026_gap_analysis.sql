-- =============================================================================
-- 0026: 갭 분석 (해외 수요 ↔ 국내 성과 카드)
--   code_gap_type       갭 종류 4가지
--   gap_run             갭 분석 한 번 실행 (왜 돌았는지·규칙 값 고정)
--   gap_finding         갭 하나 (해외 수요 하나 × 갭 종류 하나)
--   gap_finding_card    갭 근거가 된 국내 성과 카드
--   gap_pathway         갭을 메우는 제안 경로 (6대 연계유형 또는 신규 기획수요)
-- 규칙
--   - 갭은 항상 초안(DRAFT)으로 만들어지고, 확정·기각은 DEPT_REVIEWER/ADMIN 만 한다.
--   - 갭의 보안등급은 해외 수요와 근거 카드 중 가장 높은 등급보다 낮을 수 없다.
--   - 새 실행이 같은 해외 수요를 다시 보면 이전 초안은 SUPERSEDED 로 바뀐다 (확정·기각은 남긴다).
-- =============================================================================
SET search_path = ax, public;

