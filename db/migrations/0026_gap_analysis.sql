CREATE TABLE ax.gap_run (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_kind   text NOT NULL CHECK (trigger_kind IN ('MANUAL','NEW_DEMAND','NEW_CARD','RULE_CHANGE')),
    demand_ids     bigint[] NOT NULL,                     -- 이번에 본 해외 수요
    model_id       smallint NOT NULL REFERENCES ax.embedding_model(id),
    rule_snapshot  jsonb NOT NULL,                        -- 판정에 쓴 기준값 (나중에 조정 이력 비교)
    finding_count  integer NOT NULL DEFAULT 0,
    note           text,
    started_by     bigint REFERENCES ax.app_user(id),
    started_at     timestamptz NOT NULL DEFAULT now(),
    finished_at    timestamptz
);

CREATE TABLE ax.gap_finding (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gap_run_id         bigint NOT NULL REFERENCES ax.gap_run(id) ON DELETE CASCADE,
    overseas_demand_id bigint NOT NULL REFERENCES ax.overseas_demand(id) ON DELETE CASCADE,
    gap_type_code      text NOT NULL REFERENCES ax.code_gap_type(code),
    severity           numeric(5,4) NOT NULL CHECK (severity BETWEEN 0 AND 1),  -- 갭 크기
    score              numeric(5,4) NOT NULL CHECK (score BETWEEN 0 AND 1),     -- 크기 × 확신도 × 시급성
    best_similarity    numeric(5,4),                       -- 가장 가까운 국내 성과의 유사도
    summary            text NOT NULL,                      -- 한 줄 설명 (규칙 문장)
    detail             jsonb NOT NULL DEFAULT '{}'::jsonb, -- 성능 비교·미해결 과제 등 근거 스냅샷
    security_code      text NOT NULL DEFAULT 'PUBLIC' REFERENCES ax.code_security_level(code),
    status             text NOT NULL DEFAULT 'DRAFT'
                       CHECK (status IN ('DRAFT','CONFIRMED','REJECTED','SUPERSEDED')),
    decided_by         bigint REFERENCES ax.app_user(id),
    decided_at         timestamptz,
    decision_reason    text,
    maybe_resolved_at  timestamptz,                        -- 확정된 갭이 이후 실행에서 안 나오면 "해소 후보"
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (gap_run_id, overseas_demand_id, gap_type_code),
    CHECK ((status IN ('CONFIRMED','REJECTED')) = (decided_by IS NOT NULL))
);
CREATE INDEX gap_finding_demand ON ax.gap_finding(overseas_demand_id);
CREATE INDEX gap_finding_open ON ax.gap_finding(status) WHERE status IN ('DRAFT','CONFIRMED');

CREATE TABLE ax.gap_finding_card (
    finding_id   bigint NOT NULL REFERENCES ax.gap_finding(id) ON DELETE CASCADE,
    card_id      bigint NOT NULL REFERENCES ax.achievement_card(id),
    similarity   numeric(5,4),
    role         text NOT NULL DEFAULT 'NEAREST' CHECK (role IN ('NEAREST','EVIDENCE')),
    note         text,
    PRIMARY KEY (finding_id, card_id)
);
CREATE INDEX gap_finding_card_card ON ax.gap_finding_card(card_id);

CREATE TABLE ax.gap_pathway (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id        bigint NOT NULL REFERENCES ax.gap_finding(id) ON DELETE CASCADE,
    linkage_type_code text REFERENCES ax.code_linkage_type(code),   -- NULL = 신규 기획수요
    description       text NOT NULL,
    card_ids          bigint[] NOT NULL DEFAULT '{}',              -- 이어 갈 국내 성과
    sort_order        smallint NOT NULL DEFAULT 0
);
CREATE INDEX gap_pathway_finding ON ax.gap_pathway(finding_id);

-- 확정·기각은 DEPT_REVIEWER/ADMIN 만, 초안으로 되돌리기 금지
CREATE OR REPLACE FUNCTION ax.validate_gap_decision() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status AND NEW.status IN ('CONFIRMED','REJECTED') THEN
        IF OLD.status <> 'DRAFT' THEN
            RAISE EXCEPTION '갭 % 은(는) 이미 % 상태라 판정할 수 없습니다', OLD.id, OLD.status
                USING ERRCODE = 'check_violation';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM ax.user_role
                        WHERE user_id = NEW.decided_by AND role_code IN ('DEPT_REVIEWER','ADMIN')) THEN
            RAISE EXCEPTION '사용자 % 은(는) 갭 판정 권한(DEPT_REVIEWER)이 없습니다', NEW.decided_by
                USING ERRCODE = 'insufficient_privilege';
        END IF;
    ELSIF NEW.status IS DISTINCT FROM OLD.status AND NEW.status = 'DRAFT' THEN
        RAISE EXCEPTION '갭 % 을(를) 초안으로 되돌릴 수 없습니다', OLD.id USING ERRCODE = 'check_violation';
    ELSIF NEW.status IS DISTINCT FROM OLD.status AND NEW.status = 'SUPERSEDED' AND OLD.status <> 'DRAFT' THEN
        RAISE EXCEPTION '판정된 갭 % 은(는) 대체할 수 없습니다', OLD.id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_gap_finding_decision BEFORE UPDATE ON ax.gap_finding
    FOR EACH ROW EXECUTE FUNCTION ax.validate_gap_decision();

-- 보안등급: 갭은 해외 수요·근거 카드 중 가장 높은 등급 이상
CREATE OR REPLACE FUNCTION ax.check_gap_security() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_id   bigint;
    v_rank smallint;
    v_need smallint;
BEGIN
    IF TG_TABLE_NAME = 'gap_finding' THEN
        v_id := NEW.id;
    ELSE
        v_id := NEW.finding_id;
    END IF;
    SELECT l.level_rank INTO v_rank
      FROM ax.gap_finding f JOIN ax.code_security_level l ON l.code = f.security_code WHERE f.id = v_id;
    SELECT max(r) INTO v_need FROM (
        SELECT l.level_rank AS r FROM ax.gap_finding f
          JOIN ax.overseas_demand d ON d.id = f.overseas_demand_id
          JOIN ax.code_security_level l ON l.code = d.security_code WHERE f.id = v_id
        UNION ALL
        SELECT l.level_rank FROM ax.gap_finding_card fc
          JOIN ax.achievement_card ac ON ac.id = fc.card_id
          JOIN ax.code_security_level l ON l.code = ac.security_code WHERE fc.finding_id = v_id) x;
    IF v_rank IS NOT NULL AND v_need IS NOT NULL AND v_rank < v_need THEN
        RAISE EXCEPTION '갭(%)의 보안등급이 근거 자료 보안등급보다 낮습니다', v_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_gap_finding_security
    AFTER INSERT OR UPDATE OF security_code ON ax.gap_finding
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ax.check_gap_security();
CREATE CONSTRAINT TRIGGER trg_gap_finding_card_security
    AFTER INSERT OR UPDATE ON ax.gap_finding_card
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ax.check_gap_security();

