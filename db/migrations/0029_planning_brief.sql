-- 과제 평가 의견 (결과평가서·중간평가·전문가·소요군 의견)
CREATE TABLE ax.project_evaluation (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    eval_kind      text NOT NULL CHECK (eval_kind IN ('RESULT','INTERIM','EXPERT','USER')),
    eval_date      date,
    grade          text,                                  -- 평가 등급 (예: 성공, 보통, 미흡)
    opinion        text NOT NULL CHECK (btrim(opinion) <> ''),  -- 평가 의견 요지
    suggestion     text,                                  -- 보완·후속 권고 (새 기획에 넣을 것의 근거)
    evaluator      text,                                  -- 평가 주체 (예: 결과평가위원회)
    document_id    bigint REFERENCES ax.source_document(id) ON DELETE SET NULL,  -- 평가서 원문
    security_code  text NOT NULL DEFAULT 'INTERNAL' REFERENCES ax.code_security_level(code),
    created_by     bigint REFERENCES ax.app_user(id),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX project_evaluation_project ON ax.project_evaluation(project_id);

CREATE OR REPLACE FUNCTION ax.check_project_evaluation_security() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_eval smallint;
    v_proj smallint;
BEGIN
    SELECT l.level_rank INTO v_eval FROM ax.code_security_level l WHERE l.code = NEW.security_code;
    SELECT l.level_rank INTO v_proj
      FROM ax.project p JOIN ax.code_security_level l ON l.code = p.security_code WHERE p.id = NEW.project_id;
    IF v_proj IS NOT NULL AND v_eval < v_proj THEN
        RAISE EXCEPTION '평가 의견의 보안등급이 과제(%)의 보안등급보다 낮습니다', NEW.project_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_project_evaluation_security BEFORE INSERT OR UPDATE OF security_code, project_id
    ON ax.project_evaluation FOR EACH ROW EXECUTE FUNCTION ax.check_project_evaluation_security();
CREATE TRIGGER trg_project_evaluation_audit AFTER INSERT OR UPDATE OR DELETE ON ax.project_evaluation
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();

