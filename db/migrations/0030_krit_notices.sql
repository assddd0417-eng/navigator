ALTER TABLE ax.announcement
    ADD COLUMN posted_on  date,     -- 게시일 (외부 공고)
    ADD COLUMN series_key text,     -- 같은 사업의 차수·재공고·연장을 묶는 키
    ADD COLUMN body_text  text;     -- 게시글 본문
CREATE INDEX announcement_series ON ax.announcement(series_key) WHERE series_key IS NOT NULL;
CREATE INDEX announcement_posted ON ax.announcement(posted_on);

CREATE TABLE ax.announcement_attachment (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id  bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    file_name        text NOT NULL,
    source_url       text NOT NULL,
    file_ext         text,
    byte_size        integer CHECK (byte_size >= 0),
    content_hash     text,                       -- 받은 파일 sha256
    text_content     text,                       -- 뽑은 글자
    parse_status     text NOT NULL CHECK (parse_status IN ('PARSED','UNSUPPORTED','FAILED','SKIPPED')),
    parse_note       text,
    fetched_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (announcement_id, source_url)
);
COMMENT ON TABLE ax.announcement_attachment IS '외부 공고 첨부. 원본 파일은 두지 않고 글자만 남긴다';
