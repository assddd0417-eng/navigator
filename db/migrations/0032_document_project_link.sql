-- 0032: 기획서·공모서 ↔ 과제 연결 (과제번호로 자료 사슬 잇기)
--   사업 기획서 → 공모서(과제 3~5개) → 연구개발계획서 → 결과보고서·평가서 를 과제번호로 묶는다.
--   code_document_type   '사업 기획서'(PROGRAM_PLAN) 추가, 사업공고 이름을 '공모서·시행계획'으로
--   project_identifier   과제의 다른 번호 (PMS·DTiMS·공모 번호가 서로 다를 때)
--   document_project_link 문서 ↔ 과제 (문서 본문에서 찾은 과제번호·과제명, 또는 직접 지정)
-- 규칙
--   - 같은 원천 시스템 안에서 같은 번호는 한 과제만 가리킨다.
--   - 자동으로 찾은 연결은 어떻게 찾았는지(번호·다른 번호·과제명)와 찾은 글자를 남긴다.
-- =============================================================================
SET search_path = ax, public;

INSERT INTO ax.code_document_type (code, name_ko, sort_order) VALUES ('PROGRAM_PLAN', '사업 기획서', 0)
ON CONFLICT (code) DO NOTHING;
UPDATE ax.code_document_type SET name_ko = '공모서·시행계획' WHERE code = 'PROGRAM_NOTICE' AND name_ko = '사업공고·시행계획';

CREATE TABLE ax.project_identifier (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    identifier         text NOT NULL CHECK (btrim(identifier) <> ''),
    source_system_code text NOT NULL REFERENCES ax.code_source_system(code),
    note               text,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_system_code, identifier)
);
CREATE INDEX project_identifier_project ON ax.project_identifier(project_id);

CREATE TABLE ax.document_project_link (
    document_id   bigint NOT NULL REFERENCES ax.source_document(id) ON DELETE CASCADE,
    project_id    bigint NOT NULL REFERENCES ax.project(id) ON DELETE CASCADE,
    link_role     text NOT NULL CHECK (link_role IN ('SUBJECT',   -- 이 과제에 대한 문서
                                                     'LISTED')),  -- 공모서·기획서에 실린 과제
    match_method  text NOT NULL CHECK (match_method IN ('PROJECT_NO','IDENTIFIER','TITLE','MANUAL')),
    matched_text  text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (document_id, project_id)
);
CREATE INDEX document_project_link_project ON ax.document_project_link(project_id);

CREATE TRIGGER trg_project_identifier_audit AFTER INSERT OR UPDATE OR DELETE ON ax.project_identifier
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();
CREATE TRIGGER trg_document_project_link_audit AFTER INSERT OR UPDATE OR DELETE ON ax.document_project_link
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row('document_id', 'project_id');
