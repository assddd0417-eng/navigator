-- 0033: 기업 입력 항목 확장
--   company_product          제품 (무기체계·부품·소재·SW·장비·서비스)
--   company_technology       보유 기술에 TRL·입력 출처 추가 (기업이 직접 입력)
--   company_support_history  정부 지원사업 참여 이력 (R&D 과제는 company_rnd_history)
--   company_evidence         기업이 올린 증빙(확인서·인정서·평가서)에서 뽑은 글자. 원본 파일은 두지 않는다
SET search_path = ax, public;

CREATE TABLE ax.company_product (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    name             text NOT NULL,
    category         text NOT NULL DEFAULT 'COMPONENT'
                     CHECK (category IN ('WEAPON_SYSTEM','COMPONENT','MATERIAL','SOFTWARE','EQUIPMENT','SERVICE','OTHER')),
    description      text,
    is_defense       boolean NOT NULL DEFAULT false,   -- 군에 납품했거나 국방용으로 개발
    customers        text,                             -- 주요 납품처 (예: 육군, 한화에어로스페이스)
    origin           text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX company_product_org ON ax.company_product(organization_id);
CREATE TRIGGER trg_company_product_updated BEFORE UPDATE ON ax.company_product
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

ALTER TABLE ax.company_technology
    ADD COLUMN trl    smallint CHECK (trl BETWEEN 1 AND 9),
    ADD COLUMN origin text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF'));
-- 이미 있던 행은 내부 시스템에서 넣은 것
UPDATE ax.company_technology SET origin = 'INTERNAL';

CREATE TABLE ax.company_support_history (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    program_name     text NOT NULL,                    -- 예: 방산 중소기업 컨설팅 지원사업
    agency           text,                             -- 예: 국방기술진흥연구소
    year             smallint CHECK (year BETWEEN 1990 AND 2100),
    result           text NOT NULL DEFAULT 'SELECTED'
                     CHECK (result IN ('APPLIED','SELECTED','COMPLETED','SUCCESS','FAILED')),
    amount_krw       bigint CHECK (amount_krw >= 0),   -- 받은 정부지원금
    announcement_id  bigint REFERENCES ax.announcement(id) ON DELETE SET NULL,
    summary          text,
    origin           text NOT NULL DEFAULT 'SELF' CHECK (origin IN ('SELF','EXTERNAL','INTERNAL','STAFF')),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX company_support_history_org ON ax.company_support_history(organization_id);
CREATE TRIGGER trg_company_support_history_updated BEFORE UPDATE ON ax.company_support_history
    FOR EACH ROW EXECUTE FUNCTION ax.set_updated_at();

CREATE TABLE ax.company_evidence (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    file_name        text NOT NULL,
    file_ext         text,
    byte_size        integer CHECK (byte_size >= 0),
    content_hash     text NOT NULL,                    -- sha256
    text_content     text,
    parse_status     text NOT NULL CHECK (parse_status IN ('PARSED','UNSUPPORTED','FAILED')),
    parse_note       text,
    detected_kind    text CHECK (detected_kind IN ('CERTIFICATION','CREDIT_RATING','UNKNOWN')),
    detected         jsonb NOT NULL DEFAULT '{}',      -- 뽑은 값 (종류·번호·날짜·등급)
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, content_hash)
);
COMMENT ON TABLE ax.company_evidence IS '기업 증빙에서 뽑은 글자. 신용평가서가 섞이므로 기업 본인과 기관 담당자만 본다';

ALTER TABLE ax.company_certification
    ADD COLUMN company_evidence_id bigint REFERENCES ax.company_evidence(id) ON DELETE SET NULL;
ALTER TABLE ax.company_credit_rating
    ADD COLUMN company_evidence_id bigint REFERENCES ax.company_evidence(id) ON DELETE SET NULL;
