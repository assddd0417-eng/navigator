-- 0034: 담당자 참여 권유
--   company_profile.outreach_consent_at  기업이 '기관 담당자의 참여 권유 메일 받기'에 동의한 시각 (끄면 NULL)
--   outreach_message                     공고별로 담당자가 보낸 권유 메일. 같은 공고·기업에는 한 번만
SET search_path = ax, public;

ALTER TABLE ax.company_profile ADD COLUMN outreach_consent_at timestamptz;

CREATE TABLE ax.outreach_message (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id     bigint NOT NULL REFERENCES ax.announcement(id) ON DELETE CASCADE,
    organization_id     bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    recommendation_id   bigint REFERENCES ax.company_recommendation(id) ON DELETE SET NULL,
    verdict             text CHECK (verdict IN ('ELIGIBLE','NEEDS_INFO')),
    email               text NOT NULL,
    note                text,                               -- 담당자가 덧붙인 말
    status              text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','FAILED')),
    error               text,
    optout_token_hash   text UNIQUE,                        -- 메일마다 새 토큰, 누르면 동의 해제
    sent_by             bigint REFERENCES ax.app_user(id),
    created_at          timestamptz NOT NULL DEFAULT now(),
    sent_at             timestamptz,
    UNIQUE (announcement_id, organization_id)
);
CREATE INDEX outreach_message_org ON ax.outreach_message(organization_id, created_at DESC);

CREATE TRIGGER trg_outreach_message_audit AFTER INSERT OR UPDATE OR DELETE ON ax.outreach_message
    FOR EACH ROW EXECUTE FUNCTION ax.audit_row();
