CREATE TABLE ax.company_login_code (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES ax.organization(id) ON DELETE CASCADE,
    email            text NOT NULL,
    code_hash        text NOT NULL,
    expires_at       timestamptz NOT NULL,
    attempts         smallint NOT NULL DEFAULT 0,
    used_at          timestamptz,
    revoked_at       timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX company_login_code_org ON ax.company_login_code(organization_id, created_at DESC);
