const { chromium } = require('playwright')
const makeMock = require('./mock.cjs')
const BASE = process.env.QA_BASE ?? 'http://localhost:5173'
const fs = require('fs'); const pathMod = require('path'); const SHOTS = pathMod.join(__dirname, 'shots'); fs.mkdirSync(SHOTS, { recursive: true })
const results = []
const ok = (name, cond, extra = '') => { results.push([cond ? 'PASS' : 'FAIL', name, extra]); }
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 }, deviceScaleFactor: 1 })
  const handle = makeMock()
  await ctx.route((u) => u.pathname.startsWith('/api/'), async (route) => {
    const req = route.request(); const u = new URL(req.url())
    const path = u.pathname.replace(/^\/api/, '')
    let body = null; try { body = req.postDataJSON() } catch {}
    const uid = Number(req.headers()['x-user-id'])
    const [status, data] = await handle(req.method(), path, u.searchParams, body, uid)
    await route.fulfill({ status, contentType: 'application/json', body: data == null ? '' : JSON.stringify(data) })
  })
  const page = await ctx.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('console', (m) => { if (m.type() === 'error' && !/status of 403|status of 404|status of 422/.test(m.text())) errors.push(m.text()) })
  const shot = (n) => page.screenshot({ path: pathMod.join(SHOTS, `${n}.png`), fullPage: true })
  const url = () => new URL(page.url()).pathname + new URL(page.url()).search
  const toastText = async () => (await page.locator('.toast').allInnerTexts()).join(' | ')
  const clearToasts = async () => { for (const b of await page.locator('.toast-close').all()) await b.click().catch(() => {}) }
  const pick = async (label) => { await page.getByRole('button', { name: new RegExp(label) }).first().click(); await page.waitForLoadState('networkidle') }
  const switchTo = async (id) => { await page.selectOption('.role-switcher select', String(id)); await page.waitForTimeout(400) }

  // 1. 로그인 전 깊은 링크 → 로그인 → 원래 화면
  await page.goto(BASE + '/reviews?view=all')
  await page.waitForFunction(() => location.pathname === '/login')
  ok('로그인 전 /reviews?view=all → 로그인 화면', url() === '/login')
  ok('로그인 화면에 "보려던 화면으로 이동" 안내', await page.getByText('보려던 화면으로').isVisible())
  await shot('01_login')
  await pick('조직 관리자·검수자')
  ok('검수자 로그인 후 원래 화면(/reviews?view=all)로 복귀', url() === '/reviews?view=all', url())
  ok('검토 목록 "전체" 탭이 켜져 있음', await page.locator('.seg button.on', { hasText: '전체' }).isVisible())
  await shot('02_reviewer_queue')
  // 새로고침 유지
  await page.reload(); await page.waitForLoadState('networkidle')
  ok('새로고침 후에도 /reviews?view=all·로그인 유지', url() === '/reviews?view=all' && await page.locator('.whoami-name').innerText() === '부서검토자')
  // 화면에 개발자 표현이 없는지
  const body1 = await page.locator('body').innerText()
  ok('개발자 표현(X-User-Id, 청크, #숫자) 없음', !/X-User-Id|청크|임베딩|#\d/.test(body1))

  // 2. 검토하기 → 추천 상세 → 뒤로
  await page.locator('a', { hasText: '검토하기' }).first().click(); await page.waitForLoadState('networkidle')
  ok('검토하기 → 추천 상세로 이동', /^\/recommendations\/\d+$/.test(url()), url())
  await shot('03_recommendation_reviewer')
  await page.getByRole('button', { name: /채택/ }).first().click()
  await page.fill('textarea', '후속형으로 적절함')
  ok('검수자는 최종 결정 체크가 기본으로 켜짐', await page.locator('.final-check input').isChecked())
  await page.getByRole('button', { name: '최종 결정 등록' }).click(); await page.waitForTimeout(500)
  ok('최종 결정 등록 → "최종 결정이 났습니다"', await page.getByText('최종 결정이 났습니다').isVisible())
  await page.getByText('← 목록으로 돌아가기').click(); await page.waitForLoadState('networkidle')
  ok('"목록으로 돌아가기" → 이전 화면(/reviews?view=all)', url() === '/reviews?view=all', url())
  await page.goForward(); await page.waitForLoadState('networkidle')
  const fwd = await page.getByText('최종 결정이 났습니다').waitFor({ timeout: 5000 }).then(() => true, () => false)
  ok('브라우저 앞으로가기 → 추천 상세 다시 열림', /^\/recommendations\//.test(url()) && fwd, url())

  // 3. 갭 분석: 목록 → 셀 → 상세 → 확정 → 뒤로
  await page.getByRole('link', { name: /해외 수요 갭 분석/ }).click(); await page.waitForLoadState('networkidle')
  ok('메뉴 → /gaps', url() === '/gaps')
  await shot('04_gap_list')
  await page.locator('.gap-cell').first().click(); await page.waitForLoadState('networkidle')
  ok('갭 칸 클릭 → /gaps/101', url() === '/gaps/101', url())
  await shot('05_gap_detail')
  await page.getByRole('button', { name: '확정하기' }).click(); await page.waitForTimeout(500)
  ok('검수자 갭 확정 → 검수 결과 표시', await page.getByText('검수 결과').isVisible())
  await page.reload(); await page.waitForLoadState('networkidle')
  ok('갭 상세 새로고침 유지', url() === '/gaps/101' && await page.getByText('검수 결과').isVisible())
  await page.getByText('← 갭 분석 목록으로').click(); await page.waitForLoadState('networkidle')
  ok('갭 상세 → 목록으로', url() === '/gaps')
  await page.getByRole('button', { name: /확정 포함 전체/ }).click()
  ok('갭 목록 보기 전환이 주소에 남음', url() === '/gaps?view=all')
  // 검수자는 다시 분석 권한 없음 → 자물쇠 + 403 토스트
  ok('검수자에게 "다시 분석" 자물쇠 표시', await page.locator('.role-hint-locked').first().isVisible())
  await clearToasts(); await page.getByRole('button', { name: /지금 다시 분석/ }).click(); await page.waitForTimeout(500)
  ok('검수자 다시 분석 → 권한 거부 알림', /지금 역할로는 할 수 없는 일/.test(await toastText()), await toastText())

  // 4. 사용자 바꾸기: 공용 화면에서는 머물고, 못 보는 화면이면 첫 화면으로
  await page.goto(BASE + '/gaps/102'); await page.waitForLoadState('networkidle')
  await switchTo(3)
  ok('갭 상세에서 전문가로 바꿈 → 같은 화면에 머묾', url() === '/gaps/102', url())
  await clearToasts(); await page.getByRole('button', { name: '확정하기' }).click(); await page.waitForTimeout(500)
  ok('전문가 갭 확정 → 권한 거부 알림 (서버 판단)', /지금 역할로는/.test(await toastText()))
  await page.goto(BASE + '/projects'); await page.waitForLoadState('networkidle')
  ok('전문가가 /projects 직접 입력 → 접근 안내 화면', await page.getByText('만 볼 수 있습니다').isVisible())
  await shot('06_forbidden')
  await page.getByRole('link', { name: '내 첫 화면으로' }).click(); await page.waitForLoadState('networkidle')
  ok('접근 안내 → 내 첫 화면(/my-tasks)', url() === '/my-tasks')
  await shot('07_expert_mytasks')

  // 5. 전문가 추천 검토: 최종 결정 체크하면 403, 해제하면 의견 등록
  await page.goto(BASE + '/recommendations/112'); await page.waitForLoadState('networkidle')
  await page.getByRole('button', { name: /보류/ }).first().click()
  ok('전문가는 최종 결정 체크가 기본 꺼짐', !(await page.locator('.final-check input').isChecked()))
  await page.locator('.final-check input').check()
  await clearToasts(); await page.getByRole('button', { name: '최종 결정 등록' }).click(); await page.waitForTimeout(500)
  ok('전문가 최종 결정 → 권한 거부', /최종판정 권한 없음/.test(await toastText()))
  await page.locator('.final-check input').uncheck()
  await page.getByRole('button', { name: '검토 의견 등록' }).click(); await page.waitForTimeout(500)
  ok('전문가 의견 등록 성공', /검토 의견을 등록했습니다/.test(await toastText()))
  await shot('08_recommendation_expert')
  // 문서 올리기 거부
  await page.getByRole('link', { name: /문서 올리기/ }).click(); await page.waitForLoadState('networkidle')
  await page.fill('input[required]', '시험 문서'); await page.fill('textarea', '문단1\n\n문단2')
  await clearToasts(); await page.getByRole('button', { name: '문서 올리기' }).click(); await page.waitForTimeout(500)
  ok('전문가 문서 올리기 → 권한 거부', /지금 역할로는/.test(await toastText()))

  // 6. 큐레이터: 문서 → 카드 → 내 할 일 발행
  await switchTo(4)
  ok('문서 올리기 화면에서 큐레이터로 → 같은 화면 유지', url() === '/documents/upload', url())
  await page.fill('input[required]', '시험 결과보고서'); await page.fill('textarea', '첫 문단\n\n둘째 문단')
  await page.getByRole('button', { name: '문서 올리기' }).click(); await page.waitForTimeout(600)
  ok('큐레이터 문서 올리기 성공', /문서를 올렸습니다/.test(await toastText()))
  await page.locator('.card', { hasText: '② 성과카드' }).locator('textarea').fill('동기 유지 시간 3배 향상')
  await page.getByRole('button', { name: '성과카드 초안 저장' }).click(); await page.waitForTimeout(600)
  ok('카드 초안 저장 → 내 할 일 링크 안내', await page.getByRole('link', { name: /내 할 일에서 발행하기/ }).isVisible())
  await shot('09_curator_upload')
  await page.getByRole('link', { name: /내 할 일에서 발행하기/ }).click(); await page.waitForLoadState('networkidle')
  ok('안내 링크 → /my-tasks', url() === '/my-tasks')
  await page.locator('button', { hasText: '확인 완료 · 발행' }).first().waitFor()
  const before = await page.locator('button', { hasText: '확인 완료 · 발행' }).count()
  await page.locator('button', { hasText: '확인 완료 · 발행' }).first().click(); await page.waitForTimeout(600)
  ok('발행 → 목록에서 빠짐', (await page.locator('button', { hasText: '확인 완료 · 발행' }).count()) === before - 1)
  await shot('10_curator_mytasks')

  // 7. 기획자: 로그아웃 → 다른 역할 화면 from 무시
  await page.getByRole('button', { name: '로그아웃' }).click(); await page.waitForFunction(() => location.pathname === '/login')
  await page.goto(BASE + '/my-tasks'); await page.waitForFunction(() => location.pathname === '/login')
  await pick('기획자')
  ok('기획자가 /my-tasks 에서 로그인 → 권한 맞는 첫 화면(/dashboard)', url() === '/dashboard', url())
  await shot('11_planner_dashboard')
  await page.locator('.todo-item').first().click(); await page.waitForLoadState('networkidle')
  ok('오늘 할 일 → 연계 후보 찾기', url() === '/projects')
  await page.locator('.select-list button', { hasText: '회전익' }).click(); await page.waitForLoadState('networkidle')
  ok('기획수요 선택이 주소에 남음', url() === '/projects?demand=2', url())
  await page.reload(); await page.waitForLoadState('networkidle')
  ok('새로고침 후 같은 기획수요 선택 유지', await page.locator('.select-list button.on', { hasText: '회전익' }).isVisible())
  await page.getByRole('button', { name: /AI로 이어 쓸 성과 찾기/ }).click(); await page.waitForTimeout(800)
  ok('AI 찾기 → 결과 회차가 주소에 남음', /demand=2&run=\d+/.test(url()), url())
  ok('상위 3건 카드 표시', (await page.locator('.top3-card').count()) === 3)
  await shot('12_planner_projects')
  await clearToasts(); await page.locator('tr', { hasText: '기존 성과 2' }).getByRole('button', { name: '전문가에게' }).click(); await page.waitForTimeout(500)
  ok('검토 요청 성공 알림', /검토를 요청했습니다/.test(await toastText()))
  await page.goBack(); await page.waitForLoadState('networkidle')
  ok('뒤로가기 → AI 찾기 전 화면(/projects?demand=2)', url() === '/projects?demand=2', url())
  await page.locator('.select-list button', { hasText: '광대역' }).click(); await page.waitForLoadState('networkidle')
  await page.goBack(); await page.waitForLoadState('networkidle')
  ok('수요 바꾼 뒤 뒤로가기 → 이전 수요', url() === '/projects?demand=2' && await page.locator('.select-list button.on', { hasText: '회전익' }).isVisible())
  await page.getByRole('button', { name: '성과카드 목록' }).click()
  ok('탭 전환이 주소에 남음', /tab=cards/.test(url()))
  await page.getByRole('button', { name: '+ 기획수요 등록' }).click()
  ok('등록 폼 열기 ?new=1', /new=1/.test(url()))
  await page.fill('input[placeholder^="예: 광대역"]', '신규 수요 시험'); await page.fill('textarea', '시험용 필요 기술')
  await page.getByRole('button', { name: '기획수요 등록' }).click(); await page.waitForTimeout(800)
  ok('등록 후 새 수요 선택·폼 닫힘', !/new=1/.test(url()) && await page.locator('.select-list button.on', { hasText: '신규 수요 시험' }).isVisible(), url())
  await shot('13_planner_new_demand')
  // 갭 상세에서 기획수요 등록 링크
  await page.goto(BASE + '/gaps/101'); await page.waitForLoadState('networkidle')
  await page.getByRole('link', { name: '기획수요로 등록' }).click(); await page.waitForLoadState('networkidle')
  ok('갭 상세 "기획수요로 등록" → 등록 폼', /\/projects\?new=1/.test(url()))
  // 잘못된 주소
  await page.goto(BASE + '/recommendations/abc'); await page.waitForLoadState('networkidle')
  ok('잘못된 추천 주소 → 안내 문구', await page.getByText('주소가 올바르지 않습니다').isVisible())
  await page.goto(BASE + '/recommendations/9999'); await page.waitForLoadState('networkidle')
  ok('없는 추천 → 안내 문구', await page.getByText('이 추천을 열 수 없습니다').isVisible())
  await page.goto(BASE + '/no-such-page'); await page.waitForLoadState('networkidle')
  ok('없는 주소 → 내 첫 화면으로', url() === '/dashboard', url())
  // 새 탭으로 연 추천 상세의 돌아가기
  const p2 = await ctx.newPage(); await p2.goto(BASE + '/recommendations/111'); await p2.waitForLoadState('networkidle')
  await p2.getByText('← 목록으로 돌아가기').click(); await p2.waitForLoadState('networkidle')
  ok('새 탭에서 연 추천 상세 → 돌아가기는 검토 목록', new URL(p2.url()).pathname === '/reviews', p2.url())
  // 모바일 폭
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto(BASE + '/gaps'); await page.waitForLoadState('networkidle')
  await shot('14_mobile_gaps')
  const sw = await page.evaluate(() => document.documentElement.scrollWidth)
  ok('휴대폰 폭에서 화면 전체 가로 스크롤 없음', sw <= 392, String(sw))

  ok('스크립트 오류 없음', errors.length === 0, errors.join(' / '))
  await browser.close()
  for (const r of results) console.log(r.join(' | '))
  console.log(`PASS ${results.filter((r) => r[0] === 'PASS').length} / ${results.length}`)
})().catch((e) => { console.error(e); for (const r of results) console.log(r.join(' | ')); process.exit(1) })
